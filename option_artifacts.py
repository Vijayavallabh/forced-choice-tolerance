#!/usr/bin/env python3
"""Detect answer-option artifacts in multiple-choice science benchmarks.

A multiple-choice item leaks if the option set alone identifies the key. For
numeric answers the usual cause is mechanical: distractors are generated by
perturbing the true value up and down, so the key lands in the interior of the
sorted option list far more often than chance allows. A solver that never
reads the question, never sees the data, and knows no biology can then exploit
the arithmetic.

This module measures that leak, cross-validates the exploiting rule so it
cannot be accused of fitting the answer key, and provides a presentation-order
negative control. Inference is clustered on the source study wherever the
benchmark identifies one.
"""
import argparse
import ast
import json
import math
import random
import re
import statistics
from collections import Counter
from pathlib import Path

NUM_RE = re.compile(r"^[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?$")
LETTER_RE = re.compile(r"^\(([A-Z])\)\s*")
N_OPTIONS = 4


def parse_number(text):
    cleaned = str(text).strip().replace(",", "").rstrip("%").replace("−", "-")
    return float(cleaned) if NUM_RE.match(cleaned) else None


def numeric_rank(options, key_index):
    """Rank of the keyed option among the sorted numeric values, or None."""
    values = [parse_number(o) for o in options]
    if len(values) != N_OPTIONS or any(v is None for v in values) or len(set(values)) < N_OPTIONS:
        return None
    order = sorted(range(N_OPTIONS), key=lambda i: values[i])
    return order.index(key_index)


# --------------------------------------------------------------------------
# inference helpers (clustered on the source study)
# --------------------------------------------------------------------------
def cluster_bootstrap_draws(clusters, statistic, reps=10000, seed=20260918):
    """Resample whole clusters and recompute the statistic. Sorted, ascending."""
    rng = random.Random(seed)
    keys = list(clusters)
    draws = []
    for _ in range(reps):
        pooled = [x for k in (rng.choice(keys) for _ in keys) for x in clusters[k]]
        value = statistic(pooled)
        if value is not None:
            draws.append(value)
    draws.sort()
    return draws


def cluster_bootstrap(clusters, statistic, reps=10000, alpha=0.05, seed=20260918):
    draws = cluster_bootstrap_draws(clusters, statistic, reps, seed)
    if not draws:
        return (None, None)
    return (draws[int(alpha / 2 * len(draws))], draws[min(len(draws) - 1, int((1 - alpha / 2) * len(draws)))])


def normal_lower_bound(draws, alpha):
    """A one-sided lower bound at level ``alpha`` from bootstrap draws.

    Read off the draws' mean and spread rather than an order statistic. The
    level that makes the audit's rule-family tests honest is small enough that
    the matching percentile sits ten draws from the end of the resample, where
    an order statistic is mostly noise; the normal approximation is stable
    there, and whether it is *right* is settled by measurement rather than by
    assumption -- ``audit_calibration.py`` runs the whole audit on files with
    no leak in them and reports how often each test fires.
    """
    if len(draws) < 2:
        return None
    spread = statistics.pstdev(draws)
    return statistics.fmean(draws) - statistics.NormalDist().inv_cdf(1 - alpha) * spread


def rate(values):
    return statistics.fmean(values) if values else None


def chi_square_uniform(counts, n_cells=N_OPTIONS):
    """Goodness of fit against a uniform key-position distribution."""
    total = sum(counts.values())
    if not total:
        return None
    expected = total / n_cells
    stat = sum((counts.get(i, 0) - expected) ** 2 / expected for i in range(n_cells))
    return {"chi2": stat, "df": n_cells - 1, "n": total,
            "p_value_upper_bound": _chi2_sf(stat, n_cells - 1)}


def _chi2_sf(stat, df):
    """Survival function for chi-square with small integer df (no SciPy needed)."""
    if stat <= 0:
        return 1.0
    if df == 3:  # regularized upper incomplete gamma, a = 3/2
        x = stat / 2
        return math.erfc(math.sqrt(x)) + 2 * math.sqrt(x / math.pi) * math.exp(-x)
    if df == 1:
        return math.erfc(math.sqrt(stat / 2))
    if df == 2:
        return math.exp(-stat / 2)
    raise ValueError(f"unsupported df={df}")


def loco_rule_accuracy(items, reps_seed=20260918):
    """Leave-one-cluster-out accuracy of 'always pick sorted rank r'.

    The rank is selected on the other clusters only, so the reported accuracy
    is not the in-sample maximum over four candidate rules.
    """
    by_cluster = {}
    for it in items:
        by_cluster.setdefault(it["cluster"], []).append(it["rank"])
    if len(by_cluster) < 2:
        return None
    hits, n, chosen = 0, 0, Counter()
    for held_out in by_cluster:
        train = Counter(r for c, rs in by_cluster.items() if c != held_out for r in rs)
        if not train:
            continue
        best = min(range(N_OPTIONS), key=lambda r: (-train.get(r, 0), r))
        chosen[best] += 1
        for r in by_cluster[held_out]:
            hits += (r == best)
            n += 1
    return {"accuracy": hits / n if n else None, "n_scored": n,
            "rule_selected_per_fold": dict(chosen), "folds": len(by_cluster)}


# --------------------------------------------------------------------------
# per-benchmark analysis
# --------------------------------------------------------------------------
def analyse(name, items, reps=10000, chance=1 / N_OPTIONS):
    """items: dicts with 'rank' (0-3) and 'cluster'."""
    if not items:
        return None
    ranks = Counter(it["rank"] for it in items)
    interior = {}
    exterior = {}
    for it in items:
        interior.setdefault(it["cluster"], []).append(1.0 if it["rank"] in (1, 2) else 0.0)
    interior_rate = rate([x for v in interior.values() for x in v])
    lo, hi = cluster_bootstrap(interior, rate, reps=reps)
    top_rank = min(range(N_OPTIONS), key=lambda r: (-ranks.get(r, 0), r))
    best = {}
    for it in items:
        best.setdefault(it["cluster"], []).append(1.0 if it["rank"] == top_rank else 0.0)
    best_rate = rate([x for v in best.values() for x in v])
    blo, bhi = cluster_bootstrap(best, rate, reps=reps)
    return {
        "benchmark": name,
        "n_numeric_items": len(items),
        "n_clusters": len(interior),
        "rank_counts": {str(r): ranks.get(r, 0) for r in range(N_OPTIONS)},
        "rank_fractions": {str(r): ranks.get(r, 0) / len(items) for r in range(N_OPTIONS)},
        "interior_rate": interior_rate,
        "interior_rate_ci95": [lo, hi],
        "interior_rate_expected": 0.5,
        "interior_excess_significant": bool(lo is not None and lo > 0.5),
        "chi_square_vs_uniform": chi_square_uniform(ranks),
        "best_single_rank_rule": {"rank": top_rank, "accuracy": best_rate,
                                   "ci95": [blo, bhi], "chance": chance,
                                   "above_chance": bool(blo is not None and blo > chance)},
        "cross_validated_rule": loco_rule_accuracy(items),
    }


