# loaders
# --------------------------------------------------------------------------
def items_from_bixbench_jsonl(path):
    items, skipped = [], 0
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            distractors = row.get("distractors") or []
            if isinstance(distractors, str):
                try:
                    distractors = ast.literal_eval(distractors)
                except (ValueError, SyntaxError):
                    skipped += 1
                    continue
            options = [row["ideal"]] + list(distractors)
            if len(options) != N_OPTIONS:
                skipped += 1
                continue
            r = numeric_rank(options, 0)
            if r is None:
                skipped += 1
                continue
            items.append({"rank": r, "cluster": row["capsule_uuid"], "id": row["question_id"]})
    return items, skipped


def items_from_v10_results(path):
    """v1.0 baseline CSVs record the presented option list and the key letter."""
    import csv
    items, positions, skipped = [], Counter(), 0
    with open(path, encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            try:
                choices = ast.literal_eval(row["choices"])
            except (ValueError, SyntaxError, KeyError):
                skipped += 1
                continue
            letters, texts = [], []
            for choice in choices:
                m = LETTER_RE.match(str(choice).strip())
                if not m:
                    break
                letters.append(m.group(1))
                texts.append(LETTER_RE.sub("", str(choice).strip()))
            if len(letters) != N_OPTIONS or row["target"].strip() not in letters:
                skipped += 1
                continue
            key_index = letters.index(row["target"].strip())
            positions[key_index] += 1
            r = numeric_rank(texts, key_index)
            if r is None:
                skipped += 1
                continue
            items.append({"rank": r, "cluster": row["uuid"], "id": row.get("short_qid", "")})
    return items, positions, skipped


def items_from_labbench(path, cluster_fields=("source", "sources", "paper-title", "subtask")):
    """LAB-Bench subsets ship an ideal answer plus a distractor list as JSONL."""
    items, skipped = [], 0
    with open(path, encoding="utf-8") as handle:
        for i, line in enumerate(handle):
            if not line.strip():
                continue
            row = json.loads(line)
            ideal = row.get("ideal")
            distractors = row.get("distractors") or []
            if isinstance(distractors, str):
                try:
                    distractors = ast.literal_eval(distractors)
                except (ValueError, SyntaxError):
                    skipped += 1
                    continue
            options = [ideal] + list(distractors)
            if len(options) != N_OPTIONS or ideal is None:
                skipped += 1
                continue
            r = numeric_rank(options, 0)
            if r is None:
                skipped += 1
                continue
            cluster = None
            for field in cluster_fields:
                value = row.get(field)
                if isinstance(value, list):
                    value = value[0] if value else None
                if value:
                    cluster = str(value)
                    break
            items.append({"rank": r, "cluster": cluster or f"item-{i}", "id": str(row.get("id", i))})
    return items, skipped


def matched_subset_comparison(jsonl, zero_shot_dir, reps=10000):
    """Score the published no-data runs on exactly the items the rule scores.

    The model-free rule only applies to items whose four options parse as
    distinct numbers. Comparing its accuracy against a model's accuracy over
    the full question set would be comparing different populations, so this
    restricts both sides to the same items.
    """
    import csv

    rows, numeric = {}, {}
    with open(jsonl, encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            qid = row["question_id"].lower()
            rows[qid] = row
            distractors = row.get("distractors") or []
            if isinstance(distractors, str):
                try:
                    distractors = ast.literal_eval(distractors)
                except (ValueError, SyntaxError):
                    distractors = []
            options = [row.get("ideal")] + list(distractors)
            if len(options) == N_OPTIONS:
                rank = numeric_rank(options, 0)
                if rank is not None:
                    numeric[qid] = {"rank": rank, "cluster": row["capsule_uuid"]}

    out = {"n_matched_items": len(numeric), "runs": {}}
    for path in sorted(Path(zero_shot_dir).glob("*.csv")):
        clusters = {}
        with path.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle):
                qid = (row.get("uuid") or "").strip().lower()
                if qid in numeric:
                    clusters.setdefault(numeric[qid]["cluster"], []).append(
                        1.0 if str(row.get("correct", "")).strip().lower() == "true" else 0.0)
        flat = [x for g in clusters.values() for x in g]
        if not flat:
            continue
        lo, hi = cluster_bootstrap(clusters, rate, reps=reps)
        out["runs"][path.stem] = {"accuracy": rate(flat), "n": len(flat), "ci95": [lo, hi]}
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--jsonl", type=Path, default=Path("data/bixbench.jsonl"))
    parser.add_argument("--v10-results", type=Path,
                        default=Path("data/external/zero_shot_v10/"
                                     "bixbench_llm_baseline_refusal_False_mcq_gpt-4o_1.0.csv"))
    parser.add_argument("--labbench-dir", type=Path, default=Path("data/external/labbench"))
    parser.add_argument("--reps", type=int, default=10000)
    parser.add_argument("--output", type=Path, default=Path("results/option_artifacts.json"))
    args = parser.parse_args()

    report = {"n_options": N_OPTIONS, "chance": 1 / N_OPTIONS,
              "bootstrap_reps": args.reps, "benchmarks": []}

    items, skipped = items_from_bixbench_jsonl(args.jsonl)
    v15 = analyse("BixBench v1.5", items, reps=args.reps)
    v15["non_numeric_or_unparsed_items"] = skipped
    report["benchmarks"].append(v15)

    if args.v10_results.exists():
        items10, positions, skipped10 = items_from_v10_results(args.v10_results)
        v10 = analyse("BixBench v1.0", items10, reps=args.reps)
        v10["non_numeric_or_unparsed_items"] = skipped10
        v10["presentation_order_control"] = {
            "description": "Letter position of the key as actually presented to the solver.",
            "counts": {str(k): v for k, v in sorted(positions.items())},
            "chi_square_vs_uniform": chi_square_uniform(positions),
        }
        report["benchmarks"].append(v10)

    if args.labbench_dir.exists():
        for parquet in sorted(args.labbench_dir.glob("*.jsonl")):
            lb_items, lb_skipped = items_from_labbench(parquet)
            record = analyse(f"LAB-Bench {parquet.stem}", lb_items, reps=args.reps)
            if record:
                record["non_numeric_or_unparsed_items"] = lb_skipped
                report["benchmarks"].append(record)

    zs_dir = Path("data/external/zero_shot_v15")
    if args.jsonl.exists() and zs_dir.exists():
        report["matched_subset_comparison"] = matched_subset_comparison(
            args.jsonl, zs_dir, reps=args.reps)

    for rec in report["benchmarks"]:
        cv = rec.get("cross_validated_rule") or {}
        print(f"\n{rec['benchmark']}: {rec['n_numeric_items']} numeric items "
              f"in {rec['n_clusters']} clusters")
        print("  key rank among sorted options: " +
              "  ".join(f"r{r}={rec['rank_fractions'][str(r)]:.1%}" for r in range(N_OPTIONS)))
        print(f"  interior rate {rec['interior_rate']:.1%} "
              f"[{rec['interior_rate_ci95'][0]:.1%}, {rec['interior_rate_ci95'][1]:.1%}] "
              f"vs 50% expected"
              f"{'  <-- excess' if rec['interior_excess_significant'] else ''}")
        b = rec["best_single_rank_rule"]
        print(f"  model-free rule 'pick rank {b['rank']}': {b['accuracy']:.1%} "
              f"[{b['ci95'][0]:.1%}, {b['ci95'][1]:.1%}] vs {b['chance']:.0%} chance")
        if cv.get("accuracy") is not None:
            print(f"  leave-one-cluster-out cross-validated: {cv['accuracy']:.1%} "
                  f"(n={cv['n_scored']}, folds={cv['folds']})")
        if "presentation_order_control" in rec:
            ctl = rec["presentation_order_control"]["chi_square_vs_uniform"]
            print(f"  control - presented letter position: chi2={ctl['chi2']:.2f}, "
                  f"p~{ctl['p_value_upper_bound']:.3f} (uniform shuffling expected)")

    matched = report.get("matched_subset_comparison")
    if matched:
        print(f"\nOn the same {matched['n_matched_items']} numeric items, no data:")
        for name, rec in sorted(matched["runs"].items(), key=lambda kv: -kv[1]["accuracy"]):
            if "mcq-refusal-False" in name:
                print(f"  {name:52s} {rec['accuracy']:.1%} "
                      f"[{rec['ci95'][0]:.1%}, {rec['ci95'][1]:.1%}]")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"\nwrote {args.output}")


if __name__ == "__main__":
    main()
