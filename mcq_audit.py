#!/usr/bin/env python3
"""Audit — and repair — answer-option leakage in a multiple-choice benchmark.

Run this on a released question file before publishing it. It answers one
question: can a solver that never reads the question, never sees the data, and
knows no science pick the keyed answer more often than chance?

    python3 mcq_audit.py --jsonl data/bixbench.jsonl \
        --key-field ideal --distractor-field distractors --cluster-field capsule_uuid

Two rule families are tested. The *numeric* family exploits the geometry that
arises when distractors are generated by perturbing the true value: the key
ends up in the interior of the sorted options. The *surface* family exploits
option length, stem overlap, and lexical distinctiveness. Both are selected by
leave-one-cluster-out cross-validation, so a family with no generalising rule
reports chance no matter how many members it holds.

``--repair`` writes a corrected file. The repair does not touch the keyed
answers, only where the distractors sit relative to them: it redraws each
item's key rank uniformly and rescales the distractors to match. Presentation
shuffling cannot fix this leak, because the leak is in the values rather than
in their order.

``--two-channel`` repairs the key's rank under every *other* ordering the audit
measures as well, because closing one coordinate and leaving the rest open moves
solvers onto the rest. ``--search`` chooses how: the default redraws whole option
sets and keeps the closest, while ``construct`` assigns the renderings so the
written-length and roundness ranks come out exactly right, and enumerates the
ranks an item can be given rather than hunting for them.

Two cautions the tool reports on itself, both measured in
``audit_calibration.py`` and ``repair_search_ablation.py``:

* There is no one-line verdict, deliberately. The obvious one -- an OR over the
  six coordinate tests -- read ``LEAKS`` on about a sixth of files built to have
  no leak in them (``audit_calibration.py``), so it was removed rather than
  shipped with a footnote telling users to ignore it. ``coordinates_firing``
  names which tests cleared zero and is not a summary of the file. Read the
  per-coordinate bounds, each against the widest one a clean file of the same
  shape produces rather than against zero.
* A repair that meets more of its own targets is not a better repair. The rank
  a repair achieves is the rank it drew *filtered* by what the item can reach,
  so a search good enough to insist piles the keys onto the reachable ranks.
"""
