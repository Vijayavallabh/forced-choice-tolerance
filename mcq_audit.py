def coerce_list(value):
    if isinstance(value, (list, tuple)):
        return list(value)
    if isinstance(value, str):
        try:
            parsed = ast.literal_eval(value)
            return list(parsed) if isinstance(parsed, (list, tuple)) else [value]
        except (ValueError, SyntaxError):
            return [value]
    return []


def read_rows(path):
    # ``.jsonl.gz`` too: a repaired ten-option file is five megabytes plain and
    # a fifth of that gzipped, and shipping it is what lets a reader check a
    # claim about it instead of taking the number on trust.
    if path.suffixes[-2:] == [".jsonl", ".gz"]:
        with gzip.open(path, "rt", encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]
    if path.suffix == ".jsonl":
        with path.open(encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]
    if path.suffix == ".json":
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, list) else [data]
    if path.suffix == ".csv":
        with path.open(encoding="utf-8", newline="") as handle:
            return list(csv.DictReader(handle))
    raise ValueError(f"unsupported file type: {path}")


def build_items(rows, key_field, distractor_field, cluster_field, question_field,
                n_options=None):
    """Items sharing one option count, and that count.

    A file can mix option counts; comparing ranks across different counts would
    be comparing different scales, so the modal count is chosen and the rest
    reported as skipped.
    """
    candidates = []
    for i, row in enumerate(rows):
        key = row.get(key_field)
        options = [key] + coerce_list(row.get(distractor_field))
        if len(options) < 3 or any(o is None for o in options):
            continue
        candidates.append((i, row, [str(o) for o in options]))
    if not candidates:
        return [], n_options or N_OPTIONS
    if n_options is None:
        # Most common count; ties broken towards the larger count rather than
        # towards whichever row happened to come first in the file.
        counts = Counter(len(o) for _, _, o in candidates)
        n_options = max(counts, key=lambda k: (counts[k], k))

    items, without_cluster = [], 0
    for i, row, options in candidates:
        if len(options) != n_options:
            continue
        cluster = (str(row.get(cluster_field))
                   if cluster_field and row.get(cluster_field) else f"item-{i}")
        without_cluster += not (cluster_field and row.get(cluster_field))
        items.append({"row_index": i, "options": options, "key": 0,
                      "question": str(row.get(question_field, "")), "cluster": cluster,
                      "rank": rank_of(options, 0)})
    # Loud, because the silent version is worse than an error: an item with no
    # cluster becomes its own cluster, the bootstrap then resamples 661
    # independent units where the file has 39 subjects, and every interval in
    # the report comes out too narrow. We shipped a run like that.
    if cluster_field and items and without_cluster == len(items):
        print(f"warning: no row carries {cluster_field!r}; every item is its own "
              f"cluster and the intervals below are too narrow", file=sys.stderr)
    return items, n_options


