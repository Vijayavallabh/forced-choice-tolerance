def rank_rule_family(k=N_OPTIONS):
    """Candidate solvers whose choice depends only on the key's sorted rank.

    Each member is a preference vector ``b`` over the four sorted ranks, and a
    solver with preference ``b`` scores ``b_k`` on an item whose key sits at rank
    ``k``. Writing the family this way has two advantages over enumerating
    "always pick rank r".

    It covers rules that are reliably *wrong*, which leak just as much as rules
    that are reliably right: excluding one option lifts a guess from 1/4 to 1/3,
    so "never pick the largest value" scores ``(1 - p_3)/3``, which is 31% on the
    file audited here. An earlier version of this audit searched only the
    pick-one direction and reported no leak where there was one.

    And it makes the scores exact instead of sampled, since the expected score
    of a randomising rule is available in closed form.
    """
    family = {}
    for r in range(k):
        family[f"always rank {r}"] = [1.0 if i == r else 0.0 for i in range(k)]
        family[f"never rank {r}"] = [0.0 if i == r else 1.0 / (k - 1) for i in range(k)]
    interior = [1.0 if 0 < i < k - 1 else 0.0 for i in range(k)]
    family["interior only"] = [v / sum(interior) for v in interior]
    extremes = [1.0 if i in (0, k - 1) else 0.0 for i in range(k)]
    family["extremes only"] = [v / sum(extremes) for v in extremes]
    family["uniform (chance)"] = [1.0 / k] * k
    return family


# One-sided level for the two rule-family tests. Each picks a member on the
# training folds, and choosing among 23 or 36 of them is not free: at ten
# options the naive 2.5% test fired on 10% and 20% of files with no leak in
# them, and the audit's headline -- an OR over six tests -- fired on half of
# them (audit_calibration.py). This level is what brings the headline back to
# 5%, and it is set by measurement on clean files rather than by a correction
# formula, because the selection is not a clean multiple comparison.
FAMILY_ALPHA = 0.0005


def _family_interval(scored, reps, n_members):
    """A reporting CI and the strict one-sided bound the leak flag uses."""
    draws = cluster_bootstrap_draws(scored, rate, reps=reps)
    if not draws:
        return None, None, None
    lo = draws[int(0.025 * len(draws))]
    hi = draws[min(len(draws) - 1, int(0.975 * len(draws)))]
    return lo, hi, normal_lower_bound(draws, FAMILY_ALPHA)


def numeric_family_cv(items, reps, k=N_OPTIONS):
    """Leave-one-cluster-out over the rank-preference family.

    A member is chosen on the training capsules and scored on the held-out one,
    so a family with no generalising member reports chance no matter how many
    members it holds.
    """
    numeric = [it for it in items if it["rank"] is not None]
    by_cluster = {}
    for it in numeric:
        by_cluster.setdefault(it["cluster"], []).append(it)
    if len(by_cluster) < 2:
        return None
    chance = 1 / k
    family = rank_rule_family(k)
    scored, selected = {}, Counter()
    for held_out, held in by_cluster.items():
        train = [it for c, g in by_cluster.items() if c != held_out for it in g]
        best = max(family, key=lambda name: (sum(family[name][it["rank"]] for it in train),
                                             name))
        selected[best] += 1
        scored.setdefault(held_out, []).extend(family[best][it["rank"]] for it in held)
    flat = [x for v in scored.values() for x in v]
    lo, hi, strict = _family_interval(scored, reps, len(family))
    ranks = Counter(it["rank"] for it in numeric)
    shares = [ranks.get(r, 0) / len(numeric) for r in range(k)]
    interior = {c: [1.0 if 0 < it["rank"] < k - 1 else 0.0 for it in g]
                for c, g in by_cluster.items()}
    ilo, ihi = cluster_bootstrap(interior, rate, reps=reps)
    return {"n_items": len(numeric), "n_clusters": len(by_cluster),
            "n_options": k, "chance": chance,
            "rank_fractions": {str(r): shares[r] for r in range(k)},
            "interior_rate": rate([x for v in interior.values() for x in v]),
            "interior_expected": (k - 2) / k, "interior_ci95": [ilo, ihi],
            "cv_accuracy": rate(flat), "cv_ci95": [lo, hi],
            "cv_lower_bound": strict, "cv_alpha": FAMILY_ALPHA,
            # What the channel is worth to the best possible rank-only solver,
            # and to the worst: any such solver scores inside this range.
            "worst_case_score": max(shares),
            "max_geometry_credit": max(shares) - chance,
            "min_geometry_credit": min(shares) - chance,
            "rules_in_family": len(family),
            "rule_selected_per_fold": dict(selected),
            "leaks": bool(strict is not None and strict > chance)}


def surface_family_cv(items, reps, k=N_OPTIONS):
    by_cluster = {}
    for it in items:
        by_cluster.setdefault(it["cluster"], []).append(it)
    if len(by_cluster) < 2:
        return None
    # Each rule is scored in both directions: taking the option it selects, and
    # avoiding it and guessing among the rest. A rule that is reliably wrong is
    # a leak too.
    picked = {name: {it["row_index"]: surface_pick(rule, it["options"], it["question"])
                     for it in items}
              for name, rule in SURFACE_RULES.items()}
    hits = {}
    for name in SURFACE_RULES:
        hits[f"take {name}"] = {i: 1.0 if s == 0 else 0.0 for i, s in picked[name].items()}
        hits[f"avoid {name}"] = {i: 0.0 if s == 0 else 1.0 / (k - 1)
                                 for i, s in picked[name].items()}
    scored, selected = {}, Counter()
    for held_out, held in by_cluster.items():
        train = [it for c, g in by_cluster.items() if c != held_out for it in g]
        best = max(hits, key=lambda n: (sum(hits[n][it["row_index"]] for it in train), n))
        selected[best] += 1
        scored.setdefault(held_out, []).extend(hits[best][it["row_index"]] for it in held)
    flat = [x for v in scored.values() for x in v]
    lo, hi, strict = _family_interval(scored, reps, len(hits))
    return {"n_items": len(items), "n_clusters": len(by_cluster),
            "cv_accuracy": rate(flat), "cv_ci95": [lo, hi],
            "cv_lower_bound": strict, "cv_alpha": FAMILY_ALPHA,
            "rules_in_family": len(hits), "rule_selected_per_fold": dict(selected),
            "leaks": bool(strict is not None and strict > 1 / k)}


def surface_channels(items, reps, k=N_OPTIONS, cap=2000, orderings=None):
    """The same channel, measured under each non-numeric ordering of the options.

    The bound in ``choice_model.geometry_bounds`` never used the fact that the
    options were numbers: it holds for the key's rank under *any* ordering. So
    the audit measures the others too, because they are not closed by
    uniformising the numeric rank -- and, at ten options, one of them is opened
    by it.

    Each ordering is reported for all items and for the numeric ones separately,
    since the numeric items are the ones a numeric repair rewrites and therefore
    where a trade between channels would show.
    """
    from channel_survey import credit_lower_bound

    orderings = SURFACE_ORDERINGS if orderings is None else orderings
    out = {"chance": 1 / k, "orderings": {}}
    numeric = [it for it in items if it["rank"] is not None]
    # Reported separately only when they differ. On a file where every item is
    # numeric the two subsets are the same test, and running it twice doubles
    # the audit's multiplicity for nothing -- which showed up directly as a
    # higher false-positive rate in audit_calibration.py.
    subsets = ({"numeric items": numeric} if len(numeric) == len(items)
               else {"all items": items, "numeric items": numeric})
    for ordering in orderings:
        block = {}
        for label, subset in subsets.items():
            ranked = [{"rank": ordering_rank(it["options"], ordering),
                       "cluster": it["cluster"]} for it in subset]
            ranked = [item for item in ranked if item["rank"] is not None]
            if not ranked:
                continue
            counts = Counter(item["rank"] for item in ranked)
            p = [counts.get(j, 0) / len(ranked) for j in range(k)]
            bound = credit_lower_bound(ranked, k, min(reps, cap))
            block[label] = {
                "n_items": len(ranked),
                "key_by_rank_p": {str(j): p[j] for j in range(k)},
                "top_rank_share": p[k - 1],
                "max_credit_plug_in": max(p) - 1 / k,
                "credit_bound": bound,
                "leaks": bool(bound and bound["credit_lower_bound"] > 0),
            }
        out["orderings"][ordering] = block
    return out


def audit(items, reps, k=N_OPTIONS, isolation=True):
    """Six coordinate bounds on one file, and no verdict over them.

    An earlier version of this returned one ``LEAKS``/``no leak detected`` line,
    the disjunction of the six. That line fired on a sixth of provably clean
    files, because six one-sided tests at the same level have six chances to
    fire, so it is gone: what comes back is the list of coordinates that cleared
    zero, which is what a maintainer has to act on anyway.
    """
    numeric = numeric_family_cv(items, reps, k)
    surface = surface_family_cv(items, reps, k)
    lexical = surface_channels(items, reps, k) if isolation else None
    firing = []
    if numeric and numeric["leaks"]:
        firing.append("numeric rule family")
    if surface and surface["leaks"]:
        firing.append("surface rule family")
    for name, blocks in (lexical or {}).get("orderings", {}).items():
        for subset, block in blocks.items():
            if block.get("leaks"):
                firing.append(name if len(blocks) == 1 else f"{name} ({subset})")
    return {"chance": 1 / k, "n_options": k, "n_items": len(items),
            "numeric_family": numeric, "surface_family": surface,
            "surface_channels": lexical,
            "coordinates_firing": firing}


# --------------------------------------------------------------------------
SCI_RE = re.compile(r"^([-+]?\d*\.?)(\d*)[eE]([-+]?\d+)$")


def round_to_digits(value, digits):
    """``value`` rounded to ``digits`` significant digits."""
    if value == 0 or digits < 1:
        return value
    return float(f"{value:.{digits - 1}e}")


def format_like(template, value, match_digits=False):
    """Render ``value`` in the same written style as ``template``.

    A repair that reformats the distractors makes the keyed answer lexically
    distinctive, which trades a numeric leak for a surface one. Style is
    therefore copied from the option being replaced: notation, precision,
    percent sign, and thousands separators.

    Precision alone does not copy how round a value looks: a released ``0.40``
    has one significant digit, and a value drawn at random and written to two
    decimals has two, so a key written as round as its released distractors
    becomes the roundest option once they are redrawn. ``match_digits`` first
    rounds ``value`` to the template's significant digits, so the new value is
    as round as the one it replaces.
    """
    if match_digits:
        value = round_to_digits(value, max(1, int(significant_digits(template))))
    text = str(template).strip()
    percent = text.endswith("%")
    core = text.rstrip("%").replace(",", "")
    grouped = "," in str(template)

    sci = SCI_RE.match(core)
    if sci:
        digits = len(sci.group(2))
        rendered = f"{value:.{digits}e}"
        if "E" in core:
            rendered = rendered.replace("e", "E")
        # match the exponent width the template used (e.g. E-05 not E-5)
        mantissa, _, exponent = rendered.partition("e" if "e" in rendered else "E")
        sign, magnitude = exponent[0], exponent[1:].lstrip("0") or "0"
        width = max(len(sci.group(3).lstrip("+-")), len(magnitude))
        rendered = f"{mantissa}{'E' if 'E' in core else 'e'}{sign}{magnitude.zfill(width)}"
    elif "." in core:
        rendered = f"{value:.{len(core.split('.')[1])}f}"
        if match_digits and value and significant_digits(rendered) != significant_digits(template):
            # a value smaller than the template shows fewer digits at its precision: show the
            # template's significant digits instead (a count keeps its integer form, and is redrawn)
            places = max(0, int(significant_digits(template)) - 1 - math.floor(math.log10(abs(value))))
            rendered = f"{value:.{places}f}"
    else:
        rendered = f"{round(value):d}"

    if grouped:
        head, _, tail = rendered.partition(".")
        rendered = f"{int(head):,}" + (f".{tail}" if tail else "")
    return rendered + ("%" if percent else "")


def redraw_row(options, rng, target=None, templates=None, match_digits=False):
    """Regenerate the distractors so the key sits at sorted rank ``target``.

    The key's value is never changed, and the distractor *spread* is preserved:
    we keep the observed magnitude of the gaps and reposition them so the key
    lands at the requested rank. Each new distractor is written in the style of
    the one it replaces, so the redraw does not introduce a surface leak in
    place of the numeric one.

    ``target=None`` draws the rank uniformly, which is the repair. Passing the
    item's *original* rank instead yields a placebo: the distractor values move
    just as far, but the geometry that leaks is left intact. Both go through
    this one generator so the contrast between them isolates rank alone.

    ``templates`` overrides which option's written style each new distractor
    copies; by default each copies the one it replaces. Writing some
    distractors in the *key's* style is the lever the two-channel repair needs,
    because "the key is the option that does not look like the others" is
    itself an exploitable ordering (see ``repair_row_two_channel``).

    ``match_digits`` writes each new distractor with exactly the significant
    digits of the one it replaces (``format_like``), so the options' digit counts
    are the released ones and a rule that picks the roundest option scores what
    it scores on the released set; a draw that cannot be written so is redrawn.
    """
    k = len(options)
    values = [parse_number(o) for o in options]
    if any(v is None for v in values) or len(set(values)) < k:
        return None
    key = values[0]
    gaps = [abs(v - key) for v in values[1:] if abs(v - key) > 0]
    scale = statistics.fmean(gaps) if gaps else (abs(key) * 0.1 or 0.1)
    if target is None:
        target = rng.randrange(k)           # how many distractors sit below the key
    templates = list(templates) if templates is not None else list(options[1:])

    # A redrawn distractor must not be identifiable as redrawn. Generating
    # additively around the key can cross zero -- a negative p-value is an
    # obvious tell and would change the effective chance rate. When the released
    # options all share the key's sign, generate multiplicatively instead, which
    # preserves the sign and the order of magnitude of the option set.
    same_sign = key != 0 and all((v > 0) == (key > 0) for v in values)
    relative = statistics.fmean([g / abs(key) for g in gaps]) if (gaps and key) else 0.25

    # Rendering rounds to the template's precision, which can push a distractor
    # across the key and undo the intended placement. Generate, render, then
    # verify the achieved rank; widen the spread and retry if it slipped.
    # 24 attempts: the first twelve multiplicative where that applies, then
    # additive with the sign check enforced, so an item the multiplicative path
    # cannot place is still repaired rather than silently left alone.
    for attempt in range(24):
        multiplicative = same_sign and attempt < 12
        if multiplicative:
            step = max(relative, 0.05) * (1.0 + 0.5 * attempt)
            sign, magnitude = (1.0 if key > 0 else -1.0), abs(key)
            # "below the key" is a smaller magnitude for a positive key and a
            # larger one for a negative key.
            n_small = target if key > 0 else k - 1 - target
            smaller = [sign * magnitude / (1 + step * (i + 1) * rng.uniform(0.6, 1.4))
                       for i in range(n_small)]
            larger = [sign * magnitude * (1 + step * (i + 1) * rng.uniform(0.6, 1.4))
                      for i in range(k - 1 - n_small)]
            below, above = ((smaller, larger) if key > 0 else (larger, smaller))
        else:
            spread = scale * (1.0 + 0.5 * (attempt % 12))
            below = [key - spread * (i + 1) * rng.uniform(0.6, 1.4) for i in range(target)]
            above = [key + spread * (i + 1) * rng.uniform(0.6, 1.4)
                     for i in range(k - 1 - target)]
        drawn, styles = below + above, templates
        if match_digits:
            # each released distractor's style goes to the new value of the same size order, so that
            # an integer written with four digits styles a value in the thousands, not the hundreds
            size = lambda text: abs(parse_number(text) or 0.0)
            styles = [t for _, t in sorted(zip(map(size, templates), range(len(templates))), key=lambda p: p[0])]
            styles = [templates[i] for i in styles]
            drawn = sorted(drawn, key=abs)
        rendered = [format_like(t, v, match_digits) for t, v in zip(styles, drawn)]
        parsed = [parse_number(r) for r in rendered]
        if any(v is None for v in parsed):
            continue
        if match_digits and any(significant_digits(r) != significant_digits(t)
                                for r, t in zip(rendered, styles)):
            continue           # written rounder or finer than the distractor it replaces
        if same_sign and any((v > 0) != (key > 0) for v in parsed):
            continue           # a redrawn value changed sign: an obvious tell
        if len(set(parsed) | {key}) < k:
            continue           # rounding collapsed two options
        if rank_of([options[0]] + rendered, 0) == target:
            return [options[0]] + rendered
    return None                # could not place the key at the drawn rank


@lru_cache(maxsize=1 << 18)
def _cached_similarity(a, b):
    return similarity(a, b)


def _sim(a, b):
    """``text_artifacts.similarity`` memoised on the written text.

    The guided repair scores the isolation ordering thousands of times per item
    while changing one option at a time, so the same pair of strings is
    compared over and over, and the cache is keyed on the arguments in the order
    ``isolation_scores`` passes them.

    That order matters, because ``SequenceMatcher`` is not exactly symmetric:
    ``1.90E-06`` against ``0.0004`` scores 0.43 one way and 0.29 the other.
    ``isolation_scores`` therefore compares each pair once, in index order, and
    uses the value for both directions --- how unlike the others an option reads
    should be a property of the pair, not of which one the loop reached first.
    An earlier version scored both directions independently and gave the two
    options different similarities to each other; every isolation number in this
    repository was recomputed when that was fixed.
    """
    return _cached_similarity(str(a), str(b))


def isolation_scores(options):
    """How lexically isolated each option is: minus its similarity to the rest.

    This is the statistic behind the ``least_like_other_options`` rule. It is
    not about numbers at all, which is the point: the bound in
    ``choice_model.geometry_bounds`` holds for the key's rank under *any*
    ordering of the options, and closing the numeric one does not close this.

    Summed with ``math.fsum``, which is exactly rounded, rather than ``sum``,
    which is not and which changed in CPython 3.12: 3.12 sums floats with
    Neumaier compensation and earlier versions do not, so the same option set
    scored -1.5 on one interpreter and -1.4999999999999998 on another. The
    scores are dense with near-ties -- a handful of similarity ratios out of a
    small set of rationals -- so that last bit decides the key's isolation rank
    on 841 of the 38710 option sets this artifact ships or rebuilds (2.2%, and
    3.7% of MMLU-Pro's, where ten options make near-ties denser), and the rank
    is what every number in the paper is computed from. ``fsum`` agrees with
    3.12's ``sum`` on all 38710, so this fixes older interpreters without moving
    a single published number.
    """
    n = len(options)
    sim = [[0.0] * n for _ in range(n)]
    for i in range(n):
        for j in range(i + 1, n):
            sim[i][j] = sim[j][i] = _sim(options[i], options[j])
    return [-math.fsum(row) for row in sim]


def length_scores(options):
    """How long each option is written out."""
    return [float(len(str(o))) for o in options]


def significant_digits(text):
    """Significant digits in a written number: a proxy for how round it looks.

    A hand-chosen answer is often a round number and a generated distractor
    usually is not, so this orders the options by how "computed" they read.
    """
    # U+2212 MINUS SIGN, normalised the way parse_number does. Without this the
    # sign survives lstrip("+-") and is counted as a digit, so every negative
    # written that way reads one significant digit rounder than it is -- 65
    # options on MMLU-Pro, which is enough to move an item's roundness rank.
    digits = str(text).strip().replace("\u2212", "-").lstrip("+-")
    digits = digits.rstrip("%").replace(",", "")
    digits = digits.split("e")[0].split("E")[0].replace(".", "")
    return float(len(digits.lstrip("0").rstrip("0")))


def digit_scores(options):
    """Rounder options rank lower. None where an option is not a number."""
    if any(parse_number(o) is None for o in options):
        return None
    return [significant_digits(o) for o in options]


def value_scores(options):
    """Sorted numeric value, or None where the options are not distinct numbers."""
    values = [parse_number(o) for o in options]
    if any(v is None for v in values) or len(set(values)) < len(values):
        return None
    return values


# Every ordering of the options this repository measures. The bound in
# ``choice_model.geometry_bounds`` applies to each independently, so this one
# dict is both what the audit reports on and what the repair uniformises --
# auditing a coordinate you do not repair, or repairing one you do not audit,
# is how a repair comes to trade one channel for another.
ORDERINGS = {
    "sorted value": value_scores,
    "lexical isolation": isolation_scores,
    "written length": length_scores,
    "significant digits": digit_scores,
}
SURFACE_ORDERINGS = ("lexical isolation", "written length", "significant digits")


def lexicographic_scores(options):
    """Plain lexicographic order of the rendered text, for numeric options.

    ``feature_rank`` sorts on ``(score, str(option))``, so a constant score
    leaves the text as the whole sort key. This is not one of the orderings the
    audit reports -- ``held_out_orderings.py`` holds it out precisely so that it
    can be measured on a repair that never saw it -- but the key's rank under it
    is a *count* over the distractors, exactly like written length, so
    ``construct_row`` can meet a target under it when asked. See
    ``LEXICOGRAPHIC`` below for what that is for.
    """
    if any(parse_number(o) is None for o in options):
        return None
    return [0.0] * len(options)


# The name is addressable by ``ordering_rank`` and assignable by
# ``construct_row``, but it is deliberately not in ORDERINGS: adding it there
# would change what ``audit`` reports and what ``channel_attribution`` measures,
# and the point of the experiment in held_out_orderings.py is that the shipped
# repair never targeted it.
LEXICOGRAPHIC = "lexicographic order"
EXTRA_ORDERINGS = {LEXICOGRAPHIC: lexicographic_scores}

# The same score with the other tie-break. Written length ties on most items,
# so a length score does not name one ordering but a family of them, one per
# tie-break; the audit ranks (length, text ascending) and the rule family's
# `take shortest_option` takes the *later* text, which is the other member.
LENGTH_LATER = "length, later ties"
EXTRA_ORDERINGS[LENGTH_LATER] = length_scores
TIE_LATER = {LENGTH_LATER: "later"}

# What each assignable coordinate is called in a rendering menu entry. A
# coordinate is assignable exactly when the key's rank under it counts pairwise
# comparisons between the key and each distractor separately -- true of these
# four, false of lexical isolation, which is pairwise among distractors too.
ASSIGNABLE = {"written length": "shorter", "significant digits": "rounder",
              LEXICOGRAPHIC: "before", LENGTH_LATER: "shorter_later"}
COUNTED = ("written length", "significant digits")


# How many items the target distribution is fitted on, and how many passes it
# takes. Both are about the estimate, not the file: one k-vector per ordering
# settles on a few hundred items, and three damped steps were enough to bring
# every realised histogram within a point of flat on both benchmarks.
CALIBRATION_CAP = 400
CALIBRATION_STEPS = 3

# How the multi-channel repair meets its surface targets. ``sample`` and the two
# descents search for an option set; ``construct`` builds one, because written
# length and significant digits are counts over the distractors and a count can
# be assigned rather than hunted for. See repair_search_ablation.py for what the
# difference is worth.
SEARCHES = ("sample", "nearest", "guided", "construct")


def _search_options(search):
    """The two switches a searching repair takes, from its name."""
    return {"refine": search != "sample",
            "on_miss": "redraw" if search == "guided" else "nearest"}


class _LaterText:
    """Sorts the *later* text first, so a tie goes the other way."""

    __slots__ = ("text",)

    def __init__(self, text):
        self.text = text

    def __lt__(self, other):
        return self.text > other.text

    def __eq__(self, other):
        return self.text == other.text


def feature_rank(options, scores, index=0, ties="earlier"):
    """Rank of one option under a scoring function; ties break on the text.

    ``ties`` decides which way. Both are arbitrary, and that is the point: a
    score with ties does not define one ordering but a family of them, one per
    tie-break, and uniformity under one says nothing about the others. Written
    length is the case that bit us. The audit ranks by ``(length, text)``
    ascending and the construction uniformises the key's rank under exactly
    that; ``text_artifacts.pick``, which is what the surface rule family uses,
    takes the arg-max of ``(-length, text)``, so among options tied on length it
    takes the *later* text where the audit's rank takes the earlier one. On the
    repaired MMLU file the key's length rank is flat at 25.0% -- as flat as the
    repair can make it -- and "take the shortest option" still finds it 36.6% of
    the time, against 23.8% on the released file. See ``TIE_ORDERINGS``
    and held_out_orderings.py.
    """
    if ties == "later":
        order = sorted(range(len(scores)),
                       key=lambda i: (scores[i], _LaterText(str(options[i]))))
    else:
        order = sorted(range(len(scores)), key=lambda i: (scores[i], str(options[i])))
    return order.index(index)


# Orderings whose rank is taken with the opposite tie-break. Same scores, same
# definition otherwise; a different arbitrary choice where the score ties.
# Registered next to the tie-break machinery rather than at each call site: an
# ordering's tie-break is part of which ordering it is, and a caller that forgot
# to say so would silently measure the audited length coordinate twice.
TIE_ORDERINGS = dict(TIE_LATER)


def ordering_rank(options, ordering, index=0):
    """Rank of one option under a named ordering, or None where it is undefined."""
    score = ORDERINGS.get(ordering) or EXTRA_ORDERINGS[ordering]
    scores = score(options)
    if scores is None:
        return None
    return feature_rank(options, scores, index,
                        ties=TIE_ORDERINGS.get(ordering, "earlier"))


def isolation_rank(options, index=0):
    """Rank of an option by lexical isolation; ``k-1`` is "the odd one out"."""
    return feature_rank(options, isolation_scores(options), index)


def repair_row(options, rng):
    """Draw the key's rank uniformly. This is the repair."""
    return redraw_row(options, rng, target=None)


# Template schemes the two-channel search may draw from. Copying the style of
# the option being replaced keeps the file looking untouched; copying the key's
# style makes the key typical rather than odd. A mixture is what allows the
# key's isolation rank to be placed anywhere rather than pushed to one end.
def _template_schemes(options, rng, k):
    original = list(options[1:])
    key_styled = [options[0]] * (k - 1)
    shuffled = list(original)
    rng.shuffle(shuffled)
    mixed = [options[0] if rng.random() < 0.5 else t for t in original]
    return [original, key_styled, shuffled, mixed]


def _template_variants(template, key_text, span=2):
    """Written styles one redrawn distractor may take, from short to long.

    ``format_like`` reads notation, precision, percent sign and thousands
    separators off a template string and nothing else, so a synthetic template
    is as good as a real one -- and a range of them spans the written lengths
    and significant-digit counts a single value can be rendered at. The
    option's own style and the key's are both kept: the first leaves the file
    looking untouched, the second is what makes the key typical instead of the
    odd one out.
    """
    out, seen = [], set()
    for base in (str(template).strip(), str(key_text).strip()):
        if base not in seen:
            seen.add(base)
            out.append(base)
        percent = "%" if base.endswith("%") else ""
        core = base.rstrip("%").replace(",", "")
        grouped = "," in base
        sci = SCI_RE.match(core)
        width = len(sci.group(2)) if sci else (
            len(core.split(".")[1]) if "." in core else 0)
        head = None if sci else ("1,234" if grouped else "1234")
        marker = "E" if "E" in core else "e"
        for digits in range(max(0, width - span), width + span + 1):
            if head is None:
                # Keep the exponent marker the base used: a set mixing 1.9E-06
                # with 4e-04 reads as edited, and a repair that reads as edited
                # has swapped one tell for another.
                candidate = (f"1.{'0' * digits}{marker}+00" if digits
                             else f"1{marker}+00") + percent
            else:
                candidate = (f"{head}.{'0' * digits}" if digits else head) + percent
            if candidate not in seen:
                seen.add(candidate)
                out.append(candidate)
    return out


def _round_significant(value, digits):
    """``value`` rounded to ``digits`` significant figures.

    How round a distractor looks is a property of its value, not only of how it
    is printed: 12345.678 printed at any precision still reads as five
    significant figures, and no template can make it read as two. Rounding the
    value can, and a repair is free to move a distractor's value as long as the
    key's rank among them is preserved -- which is exactly what the search
    re-checks after every move.
    """
    if value == 0 or not math.isfinite(value):
        return value
    exponent = math.floor(math.log10(abs(value)))
    return round(value, -(exponent - digits + 1))


def _surface_gap(options, targets, orderings):
    """Total distance from the key's achieved surface ranks to the drawn ones."""
    total = 0
    for name in orderings:
        achieved = ordering_rank(options, name)
        if achieved is not None:
            total += abs(achieved - targets[name])
    return total


def _kick(options, rng, value_target, same_sign, key, variants):
    """Re-render two random distractors, keeping the option set legal.

    Used to restart the descent in ``_refine_surface`` from a nearby point when
    it plateaus. Returns ``None`` if no legal perturbation was found, which
    ends the search.
    """
    k = len(options)
    for _ in range(12):
        trial = list(options)
        for slot in rng.sample(range(1, k), min(2, k - 1)):
            value = parse_number(trial[slot])
            if value is None:
                continue
            trial[slot] = format_like(rng.choice(variants[slot]), value)
        parsed = [parse_number(t) for t in trial]
        if any(v is None for v in parsed) or len(set(parsed)) < k:
            continue
        if same_sign and any((v > 0) != (key > 0) for v in parsed):
            continue
        if rank_of(trial, 0) != value_target:
            continue
        return trial
    return None


def _refine_surface(options, rng, value_target, targets, orderings, sweeps=5):
    """Walk one distractor's written style at a time toward the drawn targets.

    ``repair_row_multi`` started as rejection sampling: redraw the whole option
    set, score it, keep the closest of forty-eight candidates. The acceptance
    region shrinks like ``k`` per coordinate, so what worked at four options
    did not at ten -- MMLU-Pro's written-length target was met for 13% of items
    against 33% on BixBench -- and the leak that left behind looked like a
    fifth coordinate the audit had missed. It was not. Written length and
    significant digits are each a function of how one distractor is rendered
    and of how round its value is, so with the key untouched they can be walked
    a distractor at a time; lexical isolation moves with the same lever. Every
    accepted move re-checks the *value* rank, because re-rounding a distractor
    can push it across the key and quietly undo the repair this one is built
    on.

    Returns ``(options, gap)``; a gap of zero means every drawn target was met.
    """
    k = len(options)
    values = [parse_number(o) for o in options]
    if any(v is None for v in values):
        return list(options), _surface_gap(options, targets, orderings)
    key = values[0]
    same_sign = key != 0 and all((v > 0) == (key > 0) for v in values)
    variants = [None] + [_template_variants(options[i], options[0])
                         for i in range(1, k)]

    current = list(options)
    current_gap = _surface_gap(current, targets, orderings)
    best, best_gap = list(current), current_gap
    for _ in range(sweeps):
        if best_gap == 0:
            break
        slots = list(range(1, k))
        rng.shuffle(slots)
        improved = False
        for slot in slots:
            value = parse_number(current[slot])
            if value is None:
                continue
            # Rounding a distractor can only lower its significant-digit count,
            # and trailing zeros are not significant, so rendering a round value
            # at more decimals does not raise it: "15.0000" reads as two figures,
            # not six. Moving the key's digit rank *down* needs distractors with
            # more figures than the key has, which takes a value that is not
            # round -- hence the jitter. It is small relative to the value so the
            # option stays plausible, and the rank check rejects any jitter that
            # reorders the set.
            candidates = ([value]
                          + [_round_significant(value, d) for d in (1, 2, 3, 4)]
                          + [value * (1 + rng.uniform(-0.03, 0.03))])
            for template, drawn in ((t, v) for v in candidates for t in variants[slot]):
                if drawn == 0 and value != 0:
                    continue
                text = format_like(template, drawn)
                if text == current[slot]:
                    continue
                trial = list(current)
                trial[slot] = text
                parsed = [parse_number(t) for t in trial]
                if any(v is None for v in parsed) or len(set(parsed)) < k:
                    continue
                if same_sign and any((v > 0) != (key > 0) for v in parsed):
                    continue
                if rank_of(trial, 0) != value_target:
                    continue
                gap = _surface_gap(trial, targets, orderings)
                if gap < current_gap:
                    current, current_gap, improved = trial, gap, True
                    if gap < best_gap:
                        best, best_gap = list(trial), gap
                    if best_gap == 0:
                        return best, best_gap
        if not improved:
            # A plateau is not the end: re-render two slots at random and let
            # the descent start again from there, with the incumbent kept.
            # Plain coordinate descent stalls because the coordinates are
            # coupled -- a move that fixes written length usually disturbs
            # significant digits -- and a short kick gets past that.
            kicked = _kick(current, rng, value_target, same_sign, key, variants)
            if kicked is None:
                break
            current = kicked
            current_gap = _surface_gap(current, targets, orderings)
            if current_gap < best_gap:
                best, best_gap = list(current), current_gap
    return best, best_gap


def _precedes(text, score, key_text, key_score):
    """Whether ``text`` sorts before the key under a score with a text tie-break.

    ``feature_rank`` sorts on ``(score, str(option))``, so the key's rank under
    an ordering is exactly the number of options that precede it in that sense.
    Getting the tie-break wrong here would make the construction below aim at a
    rank it then misses on the items where several options are written at the
    same length -- which is most of them.
    """
    return (score, str(text)) < (key_score, str(key_text))


def _rendering_menu(original, value, key_text, rng, variants=None):
    """Every way one distractor may be written, tagged by what it does to the ranks.

    A rendering is a choice of template (how many decimals, grouping, percent,
    scientific notation) and of how round the value itself is. Each choice fixes
    the option's written length and significant-digit count, and therefore
    whether it sits before or after the key under those two orderings. Tagging
    the menu that way turns "meet three rank targets at once" from a search into
    an assignment problem.
    """
    key_length, key_digits = float(len(str(key_text))), significant_digits(key_text)
    values = ([value] + [_round_significant(value, d) for d in (1, 2, 3, 4)]
              + [value * (1 + rng.uniform(-0.03, 0.03)) for _ in range(2)])
    templates = variants if variants is not None else _template_variants(original, key_text)
    menu, seen = [], set()
    for drawn in values:
        if drawn == 0 and value != 0:
            continue
        for template in templates:
            text = format_like(template, drawn)
            if text in seen:
                continue
            seen.add(text)
            parsed = parse_number(text)
            if parsed is None:
                continue
            menu.append({
                "text": text, "value": parsed,
                "shorter": _precedes(text, float(len(text)), key_text, key_length),
                "rounder": _precedes(text, significant_digits(text), key_text, key_digits),
                # Constant score, so the tie-break is the whole comparison --
                # which is what lexicographic order of the written option is.
                "before": _precedes(text, 0.0, key_text, 0.0),
                # Written length with the tie taken the other way, which is the
                # statistic text_artifacts.pick uses and the audit's length rank
                # does not. On MMLU the shipped repair takes this channel from
                # +1.8 to +5.8 points while closing the audited one.
                "shorter_later": ((float(len(text)), key_text)
                                  < (key_length, str(text))),
                "original": text == str(original),
            })
    return menu


def _assign_fields(with_lexicographic=False, with_tie=False):
    """The dynamic program's count fields, in the order rank tuples use."""
    return (("shorter", "rounder") + (("before",) if with_lexicographic else ())
            + (("shorter_later",) if with_tie else ()))


def _wants(names, target):
    """Targets keyed by the field each named ordering counts on.

    Passing them by name is not decoration: with four assignable coordinates and
    two of them optional, a positional tail silently feeds a length target into
    the lexicographic slot the moment the middle one is absent.
    """
    return {"want_" + ASSIGNABLE[name]: rank for name, rank in zip(names, target)}


def _assign_ranks(menus, want_shorter, want_rounder, want_before=None,
                  want_shorter_later=None):
    """Pick one rendering per distractor so the counts come out exactly.

    A dynamic program over (distractors used, options before the key on length,
    options before the key on roundness), one dimension wider for each optional
    coordinate asked for: lexicographic order of the text, and written length
    under the opposite tie-break. Every state keeps the choice that leaves the
    most distractors written exactly as the released file wrote them, so a
    feasible repair is also the least disturbing one. Returns the chosen menu
    entries, or ``None`` when the targets are jointly unreachable -- which is a
    fact about the item, not about a search budget.

    Both optional coordinates are off by default and the two-coordinate path is
    unchanged by their presence: what makes a coordinate assignable is that the
    key's rank under it counts pairwise comparisons between the key and each
    distractor separately, which value, length, roundness, lexicographic order
    and either tie-break of length all do, and lexical isolation does not.
    """
    fields, wants = ["shorter", "rounder"], [want_shorter, want_rounder]
    for field, want in (("before", want_before),
                        ("shorter_later", want_shorter_later)):
        if want is not None:
            fields.append(field)
            wants.append(want)
    fields, wants = tuple(fields), tuple(wants)
    if all(want is None for want in wants):
        return [menu[0] for menu in menus] if all(menus) else None
    n = len(menus)
    # best[state] = (kept_originals, choices), state one count per field
    best = {(0,) * len(fields): (0, [])}
    for menu in menus:
        if not menu:
            return None
        nxt = {}
        for state, (kept, choices) in best.items():
            for entry in menu:
                moved = tuple(count + entry[field]
                              for count, field in zip(state, fields))
                if any(count > n for count in moved):
                    continue
                score = kept + entry["original"]
                if moved not in nxt or score > nxt[moved][0]:
                    nxt[moved] = (score, choices + [entry])
        if not nxt:
            return None
        best = nxt
    for state, (_, choices) in best.items():
        if all(want is None or count == want for want, count in zip(wants, state)):
            return choices
    return None


def _reachable_rank_pairs(menus, n, with_lexicographic=False, with_tie=False):
    """Every rank tuple the key can be given on this item.

    ``(length, roundness)`` by default, one coordinate wider for each extra
    assignable ordering asked for -- the same enumeration, more dimensions.
    """
    fields = _assign_fields(with_lexicographic, with_tie)
    states = {(0,) * len(fields)}
    for menu in menus:
        states = {tuple(count + entry[field] for count, field in zip(state, fields))
                  for state in states for entry in menu}
        states = {state for state in states if all(count <= n for count in state)}
        if not states:
            break
    return states


def _menus_for(options, rng, value_target):
    """A seeded value draw and the rendering menu of each distractor.

    Returns ``(seeded, values, menus, same_sign)`` or ``None``.
    """
    k = len(options)
    key_value = parse_number(options[0])
    if key_value is None:
        return None
    seeded = redraw_row(options, rng, target=value_target)
    if seeded is None:
        return None
    values = [parse_number(text) for text in seeded]
    if any(value is None for value in values):
        return None
    same_sign = key_value != 0 and all((v > 0) == (key_value > 0) for v in values)
    menus = [_rendering_menu(seeded[i], values[i], options[0], rng) for i in range(1, k)]
    return seeded, values, menus, same_sign


def reachable_pairs(options, rng, value_target=None, attempts=4):
    """The (length rank, roundness rank) pairs this item's key can be given.

    Exact, not estimated: the construction below meets any pair in this set and
    no pair outside it, so the set *is* the item's repairability frontier under
    the two coordinates that resist. This is what the searches could only
    approximate, and what makes the sampler's misses explicable -- at ten
    options an independently drawn pair of targets lands outside the frontier
    for most items.
    """
    k = len(options)
    if value_target is None:
        value_target = rng.randrange(k)
    for _ in range(attempts):
        prepared = _menus_for(options, rng, value_target)
        if prepared is None:
            continue
        pairs = _reachable_rank_pairs(prepared[2], k - 1)
        if pairs:
            return pairs
    return set()


def legal_pairs(options, values, menus, same_sign, value_target, k, pairs=None,
                with_lexicographic=False, with_tie=False):
    """The (length, roundness) pairs whose assignment survives every check.

    ``_reachable_rank_pairs`` counts what the menus allow; it does not know that
    two distractors may render identically, or that rounding one may push it
    across the key and break the value rank the repair is built on. Those pairs
    are reachable on paper and not in fact, and they are not a random subset:
    the ones needing aggressive rounding fail most often, so fitting the target
    distribution on paper-reachable pairs left the key looking rounder than
    chance on a fifth of ten-option items while the repair met every rank it
    assigned. Returns ``{(length, roundness): options}``.
    """
    if pairs is None:
        pairs = _reachable_rank_pairs(menus, k - 1, with_lexicographic, with_tie)
    fields = _assign_fields(with_lexicographic, with_tie)
    out = {}
    for target in sorted(pairs):
        choices = _assign_ranks(menus, **{"want_" + field: rank
                                          for field, rank in zip(fields, target)})
        if choices is None:
            continue
        trial = [options[0]] + [entry["text"] for entry in choices]
        if _legal_row(trial, values[0], value_target, k, same_sign):
            out[target] = trial
    return out


def _ipf(frontiers, k, names, steps=200):
    """Per-rank weights making each marginal as uniform as the frontiers allow.

    ``frontiers`` is one list of reachable rank tuples per item; the tuples are
    ordered like ``names``. Drawing item ``i``'s tuple from its own list with
    probability proportional to the product of the per-rank weights gives corpus
    marginals in closed form, so iterative proportional fitting on those vectors
    needs no repair runs at all. Returns ``(weights, marginals)``.
    """
    weights = {name: [1.0] * k for name in names}
    marginals = None
    for _ in range(steps):
        shares = {name: [0.0] * k for name in names}
        for tuples in frontiers:
            mass = [math.prod(weights[name][rank] for name, rank in zip(names, item))
                    for item in tuples]
            total = math.fsum(mass)
            if not total:
                continue
            for item, value in zip(tuples, mass):
                for name, rank in zip(names, item):
                    shares[name][rank] += value / total
        marginals = {name: [value / len(frontiers) for value in shares[name]]
                     for name in names}
        for name in names:
            for rank in range(k):
                if marginals[name][rank] > 0:
                    weights[name][rank] *= (1.0 / k) / marginals[name][rank]
            scale = math.fsum(weights[name])
            weights[name] = [value / scale * k for value in weights[name]]
    return weights, marginals


def _pair_mass(weights, counted, target, k):
    """The weight a fitted vector gives one rank tuple, marginal or joint."""
    if JOINT in weights:
        index = 0
        for rank in target:
            index = index * k + rank
        return weights[JOINT][index]
    return math.prod(weights[name][rank] for name, rank in zip(counted, target))


def placeable_value_ranks(options, rng, k, attempts=2):
    """The sorted-value ranks this item's key can actually be placed at.

    ``reachability`` already reports this rate over a file; this returns the set
    for one item, because the same lesson applies to the coordinate the paper
    started with. Drawing the value target uniformly and then walking a random
    permutation of the other ranks until one works does not give a uniform
    result -- it gives the ranks the item can reach, weighted by nothing at all,
    and at ten options the realised histogram slopes from 13.7% down to 6.7%.
    """
    reachable = set()
    for rank in range(k):
        for _ in range(attempts):
            if redraw_row(options, rng, target=rank) is not None:
                reachable.add(rank)
                break
    return reachable


# The counted coordinates can be fitted two ways, and the difference is a
# finding rather than a tuning knob. Fitting the *marginals* makes each
# ordering's rank histogram flat, which is what the audit measures and what
# \S2's bound is stated over. It does not make the rank *tuple* uniform: an
# item's frontier is not a product set, so drawing from it with marginal
# weights leaves the pair dependent, and a solver that reads the pair is not
# covered by the per-ordering bound. ``joint=True`` fits one weight per
# reachable (length, roundness) cell instead, which flattens the joint at the
# cost of the marginals no longer being separately optimal. learned_probe.py is
# what found this; results/joint_draw.json is what it is worth.
JOINT = "joint rank cell"


def fit_pair_weights(numeric, k, seed, cap=CALIBRATION_CAP, steps=200,
                     with_lexicographic=False, joint=False, with_tie=False):
    """Target weights that flatten all three surface marginals, fitted exactly.

    Two passes, because the coordinates cost different amounts to enumerate.
    Written length and roundness are counts, so an item's whole frontier of
    (length, roundness) pairs enumerates in one dynamic program; those are fitted
    first, over the *complete* frontier of every sampled item. Isolation is
    pairwise, so its reachable set has to be surveyed once the pair is fixed;
    that pass draws each item's pair from the fitted weights and surveys from
    there, which is one survey per item rather than one per pair.

    Fitting the pair weights on a *sample* of each frontier is the mistake this
    two-pass version fixes: the repair draws from the full frontier, so weights
    fitted on twelve of forty-eight pairs sent a fifth of ten-option keys onto
    one written-length rank while the repair met every rank it assigned.

    Returns ``(weights, diagnostics)``, the diagnostics reporting the attainable
    uniformity -- the honest form of the repair's guarantee.
    """
    rng = random.Random(seed if isinstance(seed, int) else int(
        hashlib.sha256(str(seed).encode("utf-8")).hexdigest()[:12], 16))
    sample = (list(numeric) if len(numeric) <= cap else rng.sample(numeric, cap))
    prepared, value_sets = [], []
    for item in sample:
        options = item["options"] if isinstance(item, dict) else item
        placeable = placeable_value_ranks(options, rng, k)
        if placeable:
            value_sets.append([(rank,) for rank in sorted(placeable)])
        value_target = (rng.choice(sorted(placeable)) if placeable
                        else rng.randrange(k))
        ready = _menus_for(options, rng, value_target)
        if ready is None:
            continue
        _, values, menus, same_sign = ready
        legal = legal_pairs(options, values, menus, same_sign, value_target, k,
                            with_lexicographic=with_lexicographic, with_tie=with_tie)
        if legal:
            prepared.append((options, values, menus, same_sign, value_target, legal))
    if not prepared:
        return None, None

    counted = (COUNTED + ((LEXICOGRAPHIC,) if with_lexicographic else ())
               + ((LENGTH_LATER,) if with_tie else ()))
    if joint:
        width = k ** len(counted)

        def flatten(target):
            index = 0
            for rank in target:
                index = index * k + rank
            return (index,)

        weights, marginals = _ipf(
            [[flatten(target) for target in sorted(legal)] for *_, legal in prepared],
            width, (JOINT,), steps)
    else:
        weights, marginals = _ipf([sorted(legal) for *_, legal in prepared], k,
                                  counted, steps)

    isolation_sets = []
    for options, values, menus, same_sign, value_target, legal in prepared:
        pairs = sorted(legal)
        mass = [_pair_mass(weights, counted, target, k) for target in pairs]
        if not sum(mass):
            continue
        trial = legal[rng.choices(pairs, weights=mass, k=1)[0]]
        ranks = reachable_isolation(trial, menus, values[0], value_target, k,
                                    same_sign, rng,
                                    fields=_assign_fields(with_lexicographic, with_tie))
        if ranks:
            isolation_sets.append([(rank,) for rank in sorted(ranks)])
    if isolation_sets:
        isolation_weights, isolation_marginal = _ipf(
            isolation_sets, k, ("lexical isolation",), steps)
        weights["lexical isolation"] = isolation_weights["lexical isolation"]
        marginals["lexical isolation"] = isolation_marginal["lexical isolation"]
    if value_sets:
        value_weights, value_marginal = _ipf(value_sets, k, ("sorted value",), steps)
        weights["sorted value"] = value_weights["sorted value"]
        marginals["sorted value"] = value_marginal["sorted value"]

    return weights, {
        "n_items_fitted": len(prepared),
        "n_isolation_surveyed": len(isolation_sets),
        "mean_frontier_size": statistics.fmean(len(legal) for *_, legal in prepared),
        "mean_placeable_value_ranks": (statistics.fmean(len(s) for s in value_sets)
                                       if value_sets else None),
        "mean_isolation_reach": (statistics.fmean(len(s) for s in isolation_sets)
                                 if isolation_sets else None),
        "widest_attainable_rank_share": {name: max(values)
                                         for name, values in marginals.items()},
    }


def construct_row(options, rng, value_target=None, targets=None,
                  orderings=SURFACE_ORDERINGS, attempts=8, sweeps=3,
                  pair_weights=None):
    """Build an option set that meets the drawn ranks, rather than hunting for one.

    The searches in ``repair_row_multi`` treat "uniformise the key's rank under
    every ordering" as an optimisation problem, and that is the mistake: written
    length and significant digits are each a *count* over the distractors, so the
    targets can be met by assignment. Only the value rank needs generating, and
    lexical isolation -- which is pairwise and does not decompose -- needs the
    local pass at the end.

    Returns ``(options, value_rank, {ordering: achieved}, targets)`` or ``None``.
    Unlike the searches, a ``None`` here means the targets are genuinely out of
    reach for this item and not that a budget ran out.
    """
    k = len(options)
    key = options[0]
    if value_target is None:
        value_target = rng.randrange(k)
    if targets is None:
        targets = {name: rng.randrange(k) for name in orderings}
    drawn = dict(targets)
    key_value = parse_number(key)
    if key_value is None:
        return None
    # Which counts the assignment has to hit. Lexicographic order joins them
    # only when the caller asks for it: the shipped repair does not, which is
    # what makes held_out_orderings.py's measurement of it a held-out one.
    with_lex = LEXICOGRAPHIC in orderings or LEXICOGRAPHIC in drawn
    with_tie = LENGTH_LATER in orderings or LENGTH_LATER in drawn
    assigned = (COUNTED + ((LEXICOGRAPHIC,) if with_lex else ())
                + ((LENGTH_LATER,) if with_tie else ()))
    fields = _assign_fields(with_lex, with_tie)
    for _ in range(attempts):
        prepared = _menus_for(options, rng, value_target)
        if prepared is None:
            continue
        _, values, menus, same_sign = prepared
        if pair_weights is not None:
            # Draw from this item's own frontier instead of asking for a target
            # it may not have. Uniform *targets* and uniform *results* are
            # different things, and only the second is what the bound needs.
            legal = legal_pairs(options, values, menus, same_sign, value_target, k,
                                with_lexicographic=with_lex, with_tie=with_tie)
            if not legal:
                continue
            pairs = sorted(legal)
            mass = [_pair_mass(pair_weights, assigned, target, k) for target in pairs]
            if not sum(mass):
                continue
            chosen = rng.choices(pairs, weights=mass, k=1)[0]
            trial = legal[chosen]
            # Only for coordinates the caller asked to repair: --orderings exists
            # so a deliberately partial repair can be reproduced, and pinning a
            # coordinate it excluded would quietly make it a different repair.
            for name, rank in zip(assigned, chosen):
                if name in drawn:
                    drawn[name] = rank
        else:
            choices = _assign_ranks(
                menus, **_wants(assigned, [drawn.get(name) for name in assigned]))
            if choices is None:
                continue
            trial = [key] + [entry["text"] for entry in choices]
            if not _legal_row(trial, key_value, value_target, k, same_sign):
                continue
        isolation_weights = (pair_weights or {}).get("lexical isolation")
        if isolation_weights is not None and "lexical isolation" in drawn:
            # Draw the third target from what *this* assignment can reach, not
            # from the corpus vector alone. Asking for an isolation rank the
            # exchange moves cannot deliver would put the near-misses back, and
            # the near-misses are the whole reason a search leaves a worse file.
            ranks = sorted(reachable_isolation(trial, menus, key_value, value_target,
                                               k, same_sign, rng, fields=fields))
            mass = [isolation_weights[rank] for rank in ranks]
            if sum(mass) > 0:
                drawn["lexical isolation"] = rng.choices(ranks, weights=mass, k=1)[0]
        trial = _tune_isolation(trial, menus, key_value, value_target, k, same_sign,
                                drawn, rng, sweeps, fields=fields)
        achieved = {name: ordering_rank(trial, name)
                    for name in set(orderings) | set(assigned)}
        return trial, value_target, achieved, drawn
    return None


def _legal_row(trial, key_value, value_target, k, same_sign):
    parsed = [parse_number(text) for text in trial]
    if any(value is None for value in parsed) or len(set(parsed)) < k:
        return False
    if same_sign and any((value > 0) != (key_value > 0) for value in parsed):
        return False
    return rank_of(trial, 0) == value_target


def _sample_entries(entries, limit, rng):
    """Up to ``limit`` of a class's renderings, chosen without replacement."""
    entries = list(entries)
    if len(entries) <= limit:
        return entries
    return rng.sample(entries, limit)


def _isolation_moves(best, menus, k, rng, partners, cap=240, per_class=3,
                     fields=("shorter", "rounder")):
    """Neighbours of an assignment that the assigned counts cannot see.

    Re-render a distractor inside its own class, or let two distractors exchange
    classes: the multiset of classes is unchanged either way, so every rank the
    assignment pinned stays exactly where it was. Yielding the moves separately
    from the objective lets the same neighbourhood be used to *survey* which
    isolation ranks an item can reach and then to walk to one of them.

    ``fields`` is what a class is, and it has to be every coordinate the
    assignment pinned. Length and roundness count a distractor's class, so a
    re-render inside a class is invisible to them; written length under the
    opposite tie-break counts the distractor's *text*, so the same re-render
    moves it. Leaving it out of the class was how the four-coordinate repair met
    its first three targets exactly and its fourth on 85.6% of MMLU's items, and
    how the five-coordinate one undid its lexicographic target on 3.3%.
    """
    by_class = []
    for menu in menus:
        table = {}
        for entry in menu:
            table.setdefault(tuple(entry[field] for field in fields), []).append(entry)
        by_class.append(table)

    def class_of(slot, text):
        for key, entries in by_class[slot - 1].items():
            if any(entry["text"] == text for entry in entries):
                return key
        return None

    # Capped: a class can hold twenty renderings and an exchange is a cross
    # product, so the full neighbourhood runs to tens of thousands of candidates
    # per call and the survey below would never finish at ten options. A sample
    # of each class is enough -- what matters is which isolation *ranks* are
    # reachable, and the ranks repeat long before the renderings do.
    yielded = 0
    for slot in rng.sample(range(1, k), k - 1):
        here = class_of(slot, best[slot])
        if here is None:
            continue
        for entry in _sample_entries(by_class[slot - 1][here], per_class, rng):
            if entry["text"] != best[slot]:
                candidate = list(best)
                candidate[slot] = entry["text"]
                yielded += 1
                yield candidate
                if yielded >= cap:
                    return
        others = [s for s in range(1, k) if s != slot]
        rng.shuffle(others)
        for other in others[:partners]:
            there = class_of(other, best[other])
            if there is None or there == here:
                continue
            for mine in _sample_entries(by_class[slot - 1].get(there, ()), per_class, rng):
                for theirs in _sample_entries(by_class[other - 1].get(here, ()),
                                              per_class, rng):
                    candidate = list(best)
                    candidate[slot], candidate[other] = mine["text"], theirs["text"]
                    yielded += 1
                    yield candidate
                    if yielded >= cap:
                        return


def reachable_isolation(trial, menus, key_value, value_target, k, same_sign, rng,
                        sweeps=3, partners=4, fields=("shorter", "rounder")):
    """Isolation ranks this assignment can be walked to, counts held exact.

    A survey rather than an optimisation: the third coordinate has no
    decomposition to assign against -- isolation is pairwise -- so its frontier
    is found by exploring the moves the first two coordinates permit.
    """
    seen = {isolation_rank(trial)}
    frontier = [list(trial)]
    for _ in range(sweeps):
        nxt = []
        for current in frontier:
            for candidate in _isolation_moves(current, menus, k, rng, partners,
                                              cap=60, per_class=2, fields=fields):
                if not _legal_row(candidate, key_value, value_target, k, same_sign):
                    continue
                rank = isolation_rank(candidate)
                if rank not in seen:
                    seen.add(rank)
                    nxt.append(candidate)
        if not nxt:
            break
        frontier = nxt[:2]
    return seen


def _tune_isolation(trial, menus, key_value, value_target, k, same_sign, targets,
                    rng, sweeps, partners=4, fields=("shorter", "rounder")):
    """Move the key's isolation rank while the assigned ranks stay exact.

    Two kinds of move keep the assignment intact. A distractor may be re-rendered
    within its own (shorter, rounder) class, which changes nothing either count
    sees. And two distractors may *exchange* classes -- one takes the other's,
    the other takes the first's -- which leaves both counts identical because the
    multiset of classes is unchanged. The second move is what makes this work:
    pinning length and roundness exactly over-determines the renderings, and
    without an exchange the first constructive repair we ran closed those two
    coordinates and pushed the leak onto isolation, which is the trade this whole
    paper is about.
    """
    target = targets.get("lexical isolation")
    if target is None:
        return trial
    best, best_gap = list(trial), abs(isolation_rank(trial) - target)
    for _ in range(sweeps):
        if best_gap == 0:
            break
        improved = False
        for candidate in _isolation_moves(best, menus, k, rng, partners,
                                          fields=fields):
            if not _legal_row(candidate, key_value, value_target, k, same_sign):
                continue
            gap = abs(isolation_rank(candidate) - target)
            if gap < best_gap:
                best, best_gap, improved = candidate, gap, True
                if best_gap == 0:
                    return best
        if not improved:
            break
    return best


def _search_once(options, rng, value_target, targets, orderings, attempts,
                 refine, budget):
    """Best candidate for one set of surface targets. ``None`` if the value
    rank itself could not be met."""
    k = len(options)
    best, refined = None, 0
    for _ in range(attempts):
        for templates in _template_schemes(options, rng, k):
            candidate = redraw_row(options, rng, target=value_target, templates=templates)
            if candidate is None:
                continue
            achieved = {name: ordering_rank(candidate, name) for name in orderings}
            gap = sum(abs(achieved[name] - targets[name]) for name in orderings
                      if achieved[name] is not None)
            if gap and refine and refined < budget:
                refined += 1
                candidate, gap = _refine_surface(candidate, rng, value_target,
                                                 targets, orderings)
                achieved = {name: ordering_rank(candidate, name) for name in orderings}
            if best is None or gap < best[0]:
                best = (gap, candidate, achieved)
            if gap == 0:
                return best
    return best


def repair_row_multi(options, rng, attempts=12, value_target=None, targets=None,
                     orderings=SURFACE_ORDERINGS, refine=True, budget=3, rounds=2,
                     on_miss="redraw"):
    """Uniformise the key's rank under sorted value *and* each named ordering.

    Uniformising the numeric rank alone regenerates the distractors from the
    key. That makes them resemble each other, and leaves the key as both the
    option least like the others and the one written differently -- trading a
    measured channel for two other measured channels. Here a target rank is
    drawn uniformly for every ordering and the generator searches for an option
    set that meets all of them at once.

    Not every drawn rank is reachable. A one-character key cannot be the
    eighth-shortest of ten options, and written length and significant digits
    are coupled -- a number with more significant figures is usually written
    longer -- so an independently drawn pair of targets can name a combination
    that no rendering of any values achieves. Where a target is out of reach the
    search redraws it from the ranks it has not yet tried, which is what the
    value repair already does for an unreachable value rank: the guarantee
    becomes "uniform over the ranks this item can reach", and the caller is told
    how often the first draw was met so the difference is visible rather than
    hidden.

    Returns ``(options, value_rank, {ordering: achieved_rank}, final_targets)``,
    or ``None`` if no candidate placed the key at the drawn value rank.
    """
    k = len(options)
    if value_target is None:
        value_target = rng.randrange(k)
    drawn = (dict(targets) if targets is not None
             else {name: rng.randrange(k) for name in orderings})
    tried = {name: {drawn[name]} for name in orderings}
    best = None
    for _ in range(rounds):
        found = _search_once(options, rng, value_target, drawn, orderings,
                             attempts, refine, budget)
        if found is None:
            break
        gap, candidate, achieved = found
        if best is None or gap < best[0]:
            best = (gap, candidate, achieved, dict(drawn))
        if gap == 0:
            return candidate, value_target, achieved, dict(drawn)
        for name in orderings:
            if achieved.get(name) != drawn[name]:
                remaining = [r for r in range(k) if r not in tried[name]]
                if remaining:
                    drawn[name] = rng.choice(remaining)
                    tried[name].add(drawn[name])
    if best is None:
        return None
    if on_miss == "redraw" and best[0]:
        # Where the targets could not all be met, hand back a plain redraw
        # rather than the closest option set the search found. The closest one
        # sits on the boundary of what this item can reach, and boundaries are
        # shared: every item that cannot reach its target fails toward the same
        # few ranks, so the misses pile up and the realised histogram spikes.
        # An unguided redraw misses in no particular direction. That is why the
        # sampler, which is far worse at hitting targets, leaves a cleaner file
        # than a descent that keeps its near-misses.
        fallback = redraw_row(options, rng, target=value_target)
        if fallback is not None:
            achieved = {name: ordering_rank(fallback, name) for name in orderings}
            return fallback, value_target, achieved, best[3]
    return best[1], value_target, best[2], best[3]


def repair_row_two_channel(options, rng, attempts=12, value_target=None,
                           isolation_target=None, refine=True, on_miss="redraw"):
    """``repair_row_multi`` restricted to lexical isolation, for callers that
    want the single extra coordinate."""
    targets = None if isolation_target is None else {"lexical isolation": isolation_target}
    result = repair_row_multi(options, rng, attempts, value_target, targets,
                              orderings=("lexical isolation",), refine=refine,
                              on_miss=on_miss)
    if result is None:
        return None
    return result[0], result[1], result[2]["lexical isolation"]


def placebo_row(options, rng, match_digits=False):
    """Move the distractor values but hold the key's rank where it was."""
    return redraw_row(options, rng, target=rank_of(options, 0), match_digits=match_digits)


def reachability(items, k, seed=0):
    """For each rank, the share of items whose key can be placed there.

    The repair's guarantee is about the distribution it draws from, and drawing
    is only possible where the arithmetic allows. Placing a key at an extreme
    rank needs ``k-1`` same-style values on one side of it, and rounding to the
    written precision of the options being replaced can collapse them: a key of
    ``0.05`` among options written to two decimals has no room for nine
    distinct values below it. With four options this almost never binds; with
    ten it binds hard at the extremes, so a maintainer should be told which
    ranks are out of reach rather than left wondering why the histogram is
    still sloped.
    """
    numeric = [it for it in items if it["rank"] is not None]
    if not numeric:
        return None
    rng = random.Random(seed)
    reached = Counter()
    for item in numeric:
        for target in range(k):
            if redraw_row(item["options"], rng, target=target) is not None:
                reached[target] += 1
    return {"n_items": len(numeric),
            "reachable_share_by_rank": {str(r): reached[r] / len(numeric)
                                        for r in range(k)},
            "mean_reachable_share": sum(reached.values()) / (len(numeric) * k),
            "note": ("share of items whose key can be placed at each rank while "
                     "keeping every option's sign and written style; a low share "
                     "at the extremes caps how uniform the repair can make the "
                     "key-rank distribution")}


def _tilt(weights, landed, k, damping=0.7, floor=0.25):
    """One step of a fitted target distribution, given where a pass landed.

    Drawing every surface target uniformly is the obvious specification and the
    wrong one. A target can only be met where the arithmetic allows it -- a
    one-character key cannot be the eighth-shortest of ten options -- so a
    search that redraws an unreachable target and tries again lands where items
    *can* go, and the realised histogram piles up there. Hitting more targets
    then leaves a worse file, which is the opposite of what a hit rate
    suggests: on BixBench the guided search met 70--96% of its targets against
    the sampler's 33--87% and reopened written length doing it.

    What the bound of Section 2 needs is a uniform *marginal*, not a uniform
    target. So ask for each rank in proportion to how badly the last pass under-produced
    it, damped because the correction does not compose -- changing the targets
    changes which of them the search can meet. Draws stay independent across
    items, which is what keeps the leave-one-cluster-out audit honest (the
    balanced-multiset version of this idea is the second failure in Appendix D);
    only the distribution they are drawn from moves.
    """
    total = sum(landed.values())
    if not total:
        return weights
    current = list(weights) if weights else [1.0 / k] * k
    updated = []
    for rank in range(k):
        share = max(landed[rank] / total, floor / k)
        updated.append(current[rank] * ((1.0 / k) / share) ** damping)
    scale = sum(updated)
    return [value / scale for value in updated]


def _draw_rank(rng, k, weights):
    """A target rank, uniform or tilted."""
    if weights is None:
        return rng.randrange(k)
    return rng.choices(range(k), weights=weights, k=1)[0]


def fit_target_weights(numeric, k, seed, refine=True, cap=CALIBRATION_CAP,
                       steps=CALIBRATION_STEPS, orderings=SURFACE_ORDERINGS,
                       on_miss="redraw"):
    """The distribution to draw surface targets from, fitted to one file.

    Runs the repair on a sample of the file's own items, sees which ranks it
    could actually reach, and tilts the next pass's targets against that; see
    ``_tilt`` for why a uniform target is not the same thing as a uniform
    result. Returns ``(weights, trace)``, where ``trace`` records the widest
    realised rank share after each step so a caller can see the fit converge --
    or fail to.

    Exposed rather than buried in ``apply_repair`` because the probe in
    ``no_data_probe.py`` repairs the same file a draw at a time and needs the
    same distribution; fitting it per item would defeat the purpose, since what
    is being corrected is a property of the corpus.
    """
    if not numeric:
        return None, []
    # Callers seed from strings as well as integers -- the probe seeds every
    # stream from a formatted label so PYTHONHASHSEED cannot reach it -- so mix
    # the seed into a stable integer rather than assuming it is one.
    base = seed if isinstance(seed, int) else int(
        hashlib.sha256(str(seed).encode("utf-8")).hexdigest()[:12], 16)
    sample = (list(numeric) if len(numeric) <= cap
              else random.Random(base ^ 0x5A3B1E).sample(numeric, cap))
    weights, trace = None, []
    for step in range(steps):
        rng = random.Random(base ^ (0x5CA1E + step))
        landed = {name: Counter() for name in orderings}
        tries = 0
        for item in sample:
            options = item["options"] if isinstance(item, dict) else item
            result = repair_row_multi(
                options, rng, value_target=rng.randrange(k),
                targets={name: _draw_rank(rng, k, weights and weights[name])
                         for name in orderings},
                orderings=orderings, refine=refine, on_miss=on_miss)
            if result is None:
                continue
            tries += 1
            for name, achieved in result[2].items():
                landed[name][achieved] += 1
        if not tries:
            break
        weights = {name: _tilt(weights and weights[name], landed[name], k)
                   for name in orderings}
        trace.append({name: max(landed[name][rank] / tries for rank in range(k))
                      for name in orderings})
    return weights, trace


def apply_repair(rows, items, distractor_field, seed, preserve_rank=False,
                 k=N_OPTIONS, two_channel=False, search="sample", calibrate=False,
                 orderings=SURFACE_ORDERINGS, joint_draw=False, match_digits=False):
    """Rewrite every numeric item's distractors. ``preserve_rank`` gives the placebo.

    Target ranks are drawn independently. Assigning them from a balanced
    multiset instead gives a flatter realised histogram, which is tempting, but
    balance is a global constraint: a rank over-represented in the held-out
    items is by construction depleted in the training items, so
    leave-one-cluster-out selection picks exactly the rank that is about to be
    scarce and the audit reads fifteen points *below* chance. That is an
    artefact of the assignment, not a property of the file, so the repair keeps
    draws independent and the guarantee is stated on the distribution rather
    than on one realisation.

    Where the drawn rank is arithmetically unreachable -- a key of 1 among
    integer-styled options has no room below it -- the remaining ranks are tried
    before the item is given up on, so coverage is not traded away.

    ``two_channel`` additionally draws a target for the key's rank under every
    surface ordering the audit measures and searches for a candidate that meets
    them all. Uniformising the numeric rank alone leaves the key as the option
    that does not look like the others, which is a second exploitable ordering,
    and at ten options the numeric-only repair makes it worse than it found it.
    ``calibrate`` runs the whole repair twice: once to learn where this file's
    items can land, then again with the surface targets drawn against that, so
    the realised histogram is flat rather than the target distribution (see
    ``_tilt``).
    """
    numeric = [it for it in items if it["rank"] is not None]
    if search not in SEARCHES:
        raise ValueError(f"unknown search {search!r}; expected one of {SEARCHES}")
    switches = _search_options(search)
    refine, on_miss = switches["refine"], switches["on_miss"]
    constructing = search == "construct"

    def one_pass(stream, weights):
        rng = random.Random(stream)
        working = numeric
        value_weights = (weights or {}).get("sorted value") if constructing else None
        if preserve_rank:
            targets = [it["rank"] for it in working]
        elif value_weights is None:
            targets = [rng.randrange(k) for _ in working]
        else:
            # The value coordinate gets the same treatment as the others: draw
            # its target from the ranks this item can actually be placed at,
            # tilted so the realised histogram comes out flat. Drawing uniformly
            # and then walking a random permutation until one rank works is what
            # left the ten-option key rank sloping from 13.7% down to 6.7%.
            targets = []
            for it in working:
                placeable = sorted(placeable_value_ranks(it["options"], rng, k))
                if not placeable:
                    targets.append(rng.randrange(k))
                    continue
                mass = [value_weights[rank] for rank in placeable]
                targets.append(rng.choices(placeable, weights=mass, k=1)[0]
                               if sum(mass) else rng.choice(placeable))
        repaired = [dict(r) for r in rows]
        changed, infeasible, off_target, unconstructible = 0, [], 0, 0
        first_hits, assigned_hits, tries = Counter(), Counter(), 0
        landed = {name: Counter() for name in orderings}
        asked = {name: Counter() for name in orderings}
        met = {name: Counter() for name in orderings}
        for it, target in zip(working, targets):
            order = [target] + [r for r in rng.sample(range(k), k) if r != target]
            for attempt, candidate in enumerate(order):
                if two_channel:
                    # Drawn here rather than inside the search so the caller can
                    # report how often the *first* draw was met, separately from
                    # how often the rank finally assigned was met: the first
                    # number measures reachability, the second is what shapes
                    # the realised histogram.
                    first = {name: _draw_rank(rng, k,
                                              None if constructing
                                              else (weights and weights[name]))
                             for name in orderings}
                    if constructing:
                        result = construct_row(it["options"], rng,
                                               value_target=candidate,
                                               targets=dict(first),
                                               orderings=orderings,
                                               pair_weights=weights)
                    else:
                        result = repair_row_multi(
                            it["options"], rng, value_target=candidate,
                            targets=dict(first), orderings=orderings,
                            refine=refine, on_miss=on_miss)
                    new_options = result[0] if result else None
                    if result:
                        tries += 1
                        for name, achieved in result[2].items():
                            first_hits[name] += (achieved == first[name])
                            assigned_hits[name] += (achieved == result[3][name])
                            landed[name][achieved] += 1
                            asked[name][first[name]] += 1
                            met[name][first[name]] += (achieved == first[name])
                else:
                    new_options = redraw_row(it["options"], rng, target=candidate,
                                             match_digits=match_digits)
                if new_options is not None:
                    repaired[it["row_index"]][distractor_field] = new_options[1:]
                    changed += 1
                    off_target += (attempt > 0)
                    break
            else:
                # Every value rank refused. For the constructive repair that
                # means no frontier anywhere, so close the coordinate that can
                # still be closed rather than shipping the item as released --
                # but only here, as a last resort. Taking this branch on the
                # *first* value rank a construction refuses would send a fifth
                # of ten-option items through a value-only redraw, and a
                # value-only redraw is exactly what leaves written length open.
                last_resort = (redraw_row(it["options"], rng) if two_channel
                               and constructing else None)
                if last_resort is not None:
                    repaired[it["row_index"]][distractor_field] = last_resort[1:]
                    changed += 1
                    off_target += 1
                    unconstructible += 1
                else:
                    infeasible.append(it["options"])
        return {"rows": repaired, "changed": changed, "infeasible": infeasible,
                "off_target": off_target, "unconstructible": unconstructible,
                "tries": tries, "landed": landed,
                "first_hits": first_hits, "assigned_hits": assigned_hits,
                "asked": asked, "met": met}

    weights, calibration = None, []
    if two_channel and constructing:
        # Nothing to estimate by running the repair: each item's frontier is
        # computed directly, so the target distribution is fitted in closed form.
        weights, frontier = fit_pair_weights(
            numeric, k, seed, with_lexicographic=LEXICOGRAPHIC in orderings,
            joint=joint_draw, with_tie=LENGTH_LATER in orderings)
        calibration = [frontier] if frontier else []
    elif two_channel and calibrate:
        weights, calibration = fit_target_weights(numeric, k, seed, refine=refine,
                                                  on_miss=on_miss, orderings=orderings)
    done = one_pass(seed, weights)

    tries = done["tries"]
    achieved = ({"first_draw": {name: done["first_hits"][name] / tries
                                for name in orderings},
                 "assigned": {name: done["assigned_hits"][name] / tries
                              for name in orderings},
                 "realised_rank_share": {
                     name: [done["landed"][name][r] / tries for r in range(k)]
                     for name in orderings},
                 # P(target met | target = r). The realised histogram is the drawn
                 # target *filtered* by this, so a search whose hit rate varies
                 # across ranks concentrates the keys wherever it is highest --
                 # which is why meeting more targets can leave a worse file.
                 "hit_rate_by_target_rank": {
                     name: [(done["met"][name][r] / done["asked"][name][r])
                            if done["asked"][name][r] else None for r in range(k)]
                     for name in orderings},
                 "calibrated": weights is not None,
                 "n_value_repaired_only": done["unconstructible"],
                 "calibration_worst_rank_share": calibration} if tries else None)
    return (done["rows"], done["changed"], done["infeasible"], done["off_target"],
            achieved)


# --------------------------------------------------------------------------
def describe(label, report):
    print(f"\n--- {label} ---")
    num, surf = report["numeric_family"], report["surface_family"]
    if num:
        k = num["n_options"]
        print(f"  numeric options: {num['n_items']} items in {num['n_clusters']} clusters "
              f"({k} options each)")
        print("    key rank: " + "  ".join(
            f"r{r}={num['rank_fractions'][str(r)]:.1%}" for r in range(k)))
        print(f"    interior rate {num['interior_rate']:.1%} "
              f"[{num['interior_ci95'][0]:.1%}, {num['interior_ci95'][1]:.1%}] "
              f"({num['interior_expected']:.0%} expected)")
        print(f"    cross-validated exploit {num['cv_accuracy']:.1%} "
              f"[{num['cv_ci95'][0]:.1%}, {num['cv_ci95'][1]:.1%}] "
              f"vs {report['chance']:.0%} chance"
              + ("   LEAKS" if num["leaks"] else ""))
        print(f"    best any rank-only solver can do: {num['worst_case_score']:.1%} "
              f"({num['max_geometry_credit'] * 100:+.1f} points over chance)")
    if surf:
        print(f"  surface rules ({surf['rules_in_family']} in family), all {surf['n_items']} items")
        print(f"    cross-validated exploit {surf['cv_accuracy']:.1%} "
              f"[{surf['cv_ci95'][0]:.1%}, {surf['cv_ci95'][1]:.1%}]"
              + ("   LEAKS" if surf["leaks"] else ""))
    channels = report.get("surface_channels")
    if channels:
        print("  the same bound under other orderings of the options "
              "(numeric items, which the repair rewrites)")
        for ordering, subsets in channels["orderings"].items():
            block = subsets.get("numeric items")
            if not block:
                continue
            bound = (block["credit_bound"] or {}).get("credit_lower_bound")
            print(f"    {ordering:20s} top rank {block['top_rank_share']:5.1%}  "
                  f"plug-in {block['max_credit_plug_in'] * 100:+5.1f}  "
                  f"bound {bound * 100:+5.1f} points"
                  + ("   LEAKS" if block["leaks"] else ""))
    firing = report["coordinates_firing"]
    # Deliberately not a verdict: six one-sided tests at the same level fire on a
    # sixth of clean files between them, so the count is a pointer to which
    # bounds to read and never a statement about the file.
    print(f"  coordinates clear of zero: {', '.join(firing) if firing else 'none'}"
          f"  ({len(firing)} of 6; on provably clean files at least one fires "
          f"about a sixth of the time -- read the bounds, not the count)")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--jsonl", type=Path, default=Path("data/bixbench.jsonl"),
                        help="question file (.jsonl, .json or .csv)")
    parser.add_argument("--key-field", default="ideal")
    parser.add_argument("--distractor-field", default="distractors")
    parser.add_argument("--question-field", default="question")
    parser.add_argument("--cluster-field", default="capsule_uuid",
                        help="group items sharing a source study; omit to treat items as independent")
    parser.add_argument("--reps", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=20260918)
    parser.add_argument("--n-options", type=int, default=None,
                        help="option count to audit (default: the file's modal count)")
    parser.add_argument("--repair", type=Path, help="write a repaired question file here")
    parser.add_argument("--two-channel", action="store_true",
                        help="also uniformise the key's rank under every surface "
                             "ordering, not only under sorted value")
    parser.add_argument("--orderings", nargs="+", choices=sorted(SURFACE_ORDERINGS),
                        default=None,
                        help="restrict --two-channel to these surface orderings. "
                             "Repairing a coordinate you do not audit, or auditing one "
                             "you do not repair, is how a repair trades one channel for "
                             "another, so this exists to reproduce the deliberately "
                             "partial repairs the paper probes")
    parser.add_argument("--no-isolation", action="store_true",
                        help="skip the lexical-isolation channel (it is the slow part)")
    parser.add_argument("--calibrate", action="store_true",
                        help="draw surface targets against the file's own reachability "
                             "rather than uniformly (mcq_audit._tilt). It helps a "
                             "guided search and does nothing for the default one")
    parser.add_argument("--search", choices=SEARCHES, default="sample",
                        help="how the multi-channel repair meets its surface targets. "
                             "'sample' keeps the best of forty-eight whole redraws; "
                             "'nearest' and 'guided' walk one distractor's written "
                             "style at a time, meet two to three times as many targets, "
                             "and leave a worse file; 'construct' assigns the renderings "
                             "so the length and roundness targets are met exactly, and "
                             "draws them from each item's own reachable set "
                             "(repair_search_ablation.py)")
    parser.add_argument("--joint-draw", action="store_true",
                        help="fit one weight per reachable (length, roundness) cell "
                             "instead of one per rank of each, so the rank *tuple* "
                             "comes out flat rather than each margin separately. "
                             "Not the shipped repair: see learned_probe.py for why "
                             "it exists and what it costs")
    parser.add_argument("--with-lexicographic", action="store_true",
                        help="repair one more coordinate: plain lexicographic order "
                             "of the written options, which held_out_orderings.py "
                             "holds out. Only the construction can meet it, because "
                             "the key's rank under it is a count over the "
                             "distractors like written length. Not part of the "
                             "shipped repair; use it to ask what a fifth "
                             "coordinate costs")
    parser.add_argument("--with-tie-break", action="store_true",
                        help="repair one more coordinate: written length with the "
                             "opposite tie-break, which is what the rule family's "
                             "`take shortest_option` actually reads. The two are "
                             "different orderings on most items -- the key ties "
                             "some distractor on length on 87%% of MMLU's -- and "
                             "the shipped repair flattens only the audited one. "
                             "Not the shipped repair; use it to ask what the "
                             "other member of the family costs")
    parser.add_argument("--output", type=Path, default=Path("results/mcq_audit.json"))
    args = parser.parse_args()
    if args.joint_draw and args.search != "construct":
        raise SystemExit("--joint-draw needs --search construct: only the "
                         "construction draws from an enumerated frontier")
    if args.with_lexicographic and args.search != "construct":
        raise SystemExit("--with-lexicographic needs --search construct: the "
                         "searching repairs have no way to meet a count exactly")
    if args.with_tie_break and args.search != "construct":
        raise SystemExit("--with-tie-break needs --search construct: the "
                         "searching repairs have no way to meet a count exactly")

    if args.orderings and args.search == "construct":
        print("note: --orderings is for the searching repairs. Every option set the "
              "construction builds has a written length and a roundness, and the "
              "construction draws them from the item's frontier, so it repairs all "
              "three surface coordinates whatever this flag says.", file=sys.stderr)
    rows = read_rows(args.jsonl)
    items, k = build_items(rows, args.key_field, args.distractor_field,
                           args.cluster_field, args.question_field, args.n_options)
    if not items:
        raise SystemExit("no multi-option items found; check --key-field and "
                         "--distractor-field")
    print(f"{len(items)} items with {k} options each "
          f"(of {len(rows)} rows; other option counts skipped)")

    before = audit(items, args.reps, k, isolation=not args.no_isolation)
    describe(f"{args.jsonl} as released", before)
    # The seed is part of what produced the file, so it goes in the report: a
    # repair is a draw, and a draw without its seed is not a result.
    report = {"file": str(args.jsonl), "n_options": k, "seed": args.seed,
              "before": before}

    if args.repair:
        repaired_rows, changed, infeasible, off_target, isolation_hit = apply_repair(
            rows, items, args.distractor_field, args.seed, k=k,
            two_channel=args.two_channel, search=args.search,
            calibrate=args.calibrate,
            orderings=(tuple(args.orderings or SURFACE_ORDERINGS)
                       + ((LEXICOGRAPHIC,) if args.with_lexicographic else ())
                       + ((LENGTH_LATER,) if args.with_tie_break else ())),
            joint_draw=args.joint_draw)
        repaired_items, _ = build_items(repaired_rows, args.key_field, args.distractor_field,
                                        args.cluster_field, args.question_field, k)
        after = audit(repaired_items, args.reps, k, isolation=not args.no_isolation)
        describe(f"after repairing {changed} numeric items", after)
        args.repair.parent.mkdir(parents=True, exist_ok=True)
        # ``.jsonl.gz`` writes gzipped, to match read_rows: a ten-option repair
        # is five megabytes plain, and a file nobody ships is a claim nobody can
        # check. mtime is pinned so the same repair gives the same bytes.
        if args.repair.suffixes[-2:] == [".jsonl", ".gz"]:
            opener = lambda: gzip.GzipFile(filename="", mode="wb", mtime=0,
                                           fileobj=args.repair.open("wb"),
                                           compresslevel=9)
            with io.TextIOWrapper(opener(), encoding="utf-8") as handle:
                for row in repaired_rows:
                    handle.write(json.dumps(row) + "\n")
        else:
            with args.repair.open("w", encoding="utf-8") as handle:
                for row in repaired_rows:
                    handle.write(json.dumps(row) + "\n")
        print(f"\nwrote {args.repair}")
        if off_target:
            print(f"  {off_target} item(s) took a different rank than assigned "
                  f"because the assigned one was unreachable")
        if infeasible:
            print(f"  {len(infeasible)} item(s) could not be placed at any rank "
                  f"and keep their released options, e.g. {infeasible[0]}")
        reach = reachability(items, k, args.seed)
        if reach:
            worst = min(reach["reachable_share_by_rank"].items(), key=lambda kv: kv[1])
            print(f"  reachability: {reach['mean_reachable_share']:.0%} of "
                  f"(item, rank) pairs placeable; hardest is rank {worst[0]} "
                  f"at {worst[1]:.0%}")
        frontier = (isolation_hit or {}).get("calibration_worst_rank_share") or []
        if frontier and isinstance(frontier[-1], dict) and "mean_frontier_size" in frontier[-1]:
            fitted = frontier[-1]
            attainable = ", ".join(
                f"{name} {share:.1%}"
                for name, share in sorted(fitted["widest_attainable_rank_share"].items()))
            print(f"  frontier: {fitted['mean_frontier_size']:.1f} reachable rank "
                  f"combinations per item, fitted on {fitted['n_items_fitted']} items")
            # What the fit *reached* on the sampled frontiers, not an infimum:
            # the repair drew flatter than this on MMLU-Pro's written length, so
            # calling it a limit would be claiming more than was computed.
            print(f"  flattest marginal the fit reached: {attainable} "
                  f"(flat is {1 / k:.1%})")
        if isolation_hit is not None and isolation_hit.get("n_value_repaired_only"):
            print(f"  {isolation_hit['n_value_repaired_only']} item(s) had no "
                  f"reachable surface target at any value rank and were repaired on "
                  f"the value coordinate only")
        if isolation_hit is not None:
            drawn = "calibrated" if isolation_hit["calibrated"] else "uniform"
            print(f"  surface targets ({args.search} search, {drawn} draw): "
                  f"first draw met / assigned rank met / widest realised rank")
            for name in sorted(isolation_hit["first_draw"]):
                share = isolation_hit["realised_rank_share"][name]
                print(f"    {name:20s} {isolation_hit['first_draw'][name]:5.0%}"
                      f" / {isolation_hit['assigned'][name]:5.0%}"
                      f" / {max(share):5.1%} (flat would be {1 / k:.1%})")
        report.update({"after_repair": after, "n_repaired": changed,
                       "reachability": reach,
                       "n_infeasible": len(infeasible),
                       "n_rank_reassigned": off_target,
                       "two_channel": bool(args.two_channel),
                       "search": args.search,
                       # What actually happened, not what was asked for: the
                       # constructive repair fits its target distribution
                       # whether or not --calibrate was passed.
                       "calibrated": bool(isolation_hit and isolation_hit["calibrated"]),
                       "tilt_requested": bool(args.calibrate),
                       "surface_target_hit_rate": isolation_hit,
                       "infeasible_examples": [list(o) for o in infeasible[:5]],
                       "repaired_orderings": (["sorted value"]
                                              + list(args.orderings or SURFACE_ORDERINGS)
                                              if args.two_channel else ["sorted value"]),
                       "repair": ((("the key's rank under sorted value and under "
                                    + ", ".join(args.orderings or SURFACE_ORDERINGS)
                                    + " all redrawn uniformly; ") if args.two_channel
                                   else "key rank redrawn uniformly; ")
                                  + "keyed answers unchanged; distractor sign, spread "
                                    "and written style preserved")})

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
