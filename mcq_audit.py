def rank_of(options, key_index=0):
    """Rank of the keyed option among the sorted values, for any option count.

    ``option_artifacts.numeric_rank`` fixes four options because that is what
    BixBench has. Benchmarks in the wild do not: MMLU-Pro has ten, AQuA-RAT
    five, and an audit tool that cannot read them is not much of a tool.
    """
    values = [parse_number(o) for o in options]
    if any(v is None for v in values) or len(set(values)) < len(values):
        return None
    return sorted(range(len(values)), key=lambda i: values[i]).index(key_index)


